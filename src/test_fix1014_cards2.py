import os
import re
import sys
import time

sys.stdout.reconfigure(encoding='utf-8')
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import glossary  # noqa: E402
import orchestrator  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
n = 0
fail = []


def ok(cond, msg):
    global n
    n += 1
    if not cond:
        fail.append(msg)


def keys(q):
    f = glossary.fixed(q)
    return (f and f['key']), [c['key'] for c in glossary.cards(q)]


def nows(s):
    return re.sub(r'\s+', '', s)


PEN, OUT, MOVE, RET = '1,500만 원', '연금외수령과 1,500만 원', '연금계좌 이전', '퇴직금 연금 수령 이점'

# 107 — 재현 입력: 55세 이상 나이·'1년에'가 있는 '빼면·인출·꺼내 쓰·찾아 쓰'는 연금수령 1,500만 원(전액 종합과세 또는 16.5% 선택)
for q in ('67세인데 연금저축에서 1년에 1,500만 원 넘게 빼면 종합과세예요?', '70세에 IRP에서 1,500만 원 넘게 인출하면 종합과세돼요?',
          '연금저축에서 1년에 1,500만 원 넘게 꺼내 쓰면 세금이 어떻게 돼요?', '65세인데 1,500만 원 넘게 찾아 쓰면 분리과세 선택할 수 있어요?',
          '60세인데 1,500만 원 넘게 인출하면 분리과세 골라야 해요?'):
    fk, ck = keys(q)
    ok(fk == PEN and ck == [PEN], f'[107] 연금수령 1,500만 원 카드: {q} → {fk} {ck}')
    ok(OUT not in ck, f'[107] 연금외수령 카드 아님: {q} → {ck}')
# 같은 원인의 변형 — 만 55세 이상 나이(만·살·이후·넘어서), 한 해 단위(매년·한 해에·1년에)
for q in ('만 58세인데 IRP에서 1,500만 원 넘게 빼면 어떻게 돼요?', '56살인데 연금저축에서 1,500만 원 넘게 출금하면 세금은?',
          '55세 이후에 1,500만 원 넘게 인출하면 종합과세돼요?', '55세 넘어서 1,500만 원 넘게 빼면 종합과세예요?',
          '매년 1,500만 원 넘게 빼면 종합과세예요?', '한 해에 1,500만 원 넘게 인출하면 종합과세돼요?', '1년에 1,500만 원 넘게 찾아 쓰면 세금은?',
          '연금 받는 중인데 1,500만 원 넘게 빼면 종합과세예요?', '연금 받다가 1,500만 원 넘게 꺼내면 종합과세돼요?',
          '45세에 퇴직했는데 60세에 1년에 1,500만 원 넘게 빼면?'):
    ok(keys(q)[1] == [PEN], f'[107] 변형도 연금수령 1,500만 원: {q} → {keys(q)}')
# 1차에서 고친 것은 그대로 — 해지·개시 전·55세 전·연금 받기 전·55세 안 된 나이는 나이·'1년에'가 있어도 연금외수령
for q in ('IRP 해지할 때 1,500만 원 넘으면 다른 소득이랑 합쳐요?', '연금 개시 전에 1,500만 원 넘게 인출하면 종합과세예요?',
          '1,500만 원 넘게 연금저축에서 빼면 세금 어떻게 돼요?', '55세 전에 IRP에서 1,500만 원 넘게 꺼내면 종합과세돼요?',
          '67세인데 연금저축 해지하면 1,500만 원 넘어도 분리과세예요?', '70세에 IRP 중도인출 1,500만 원 넘게 하면 종합과세돼요?',
          '60세인데 연금 개시 전에 1,500만 원 넘게 인출하면 종합과세예요?', '60세인데 1,500만 원 넘게 일시금으로 빼면 세금은?',
          '55세 전에 연금저축에서 1년에 1,500만 원 넘게 빼면 종합과세예요?', '50세인데 1년에 1,500만 원 넘게 빼면 종합과세예요?',
          '54살인데 1년에 1,500만 원 넘게 꺼내면 세금은?', '만 48세인데 연금저축에서 매년 1,500만 원 넘게 인출하면?',
          '연금 받기 전에 1,500만 원 넘게 빼면 종합과세 돼요?', '연금 수령 전에 1,500만 원 이상 인출하면 다른 소득이랑 합쳐요?',
          '연금저축 깨서 1,500만 원 넘게 받으면 종합과세예요?', '연금저축 깨면 1,500만 원 넘을 때 다른 소득이랑 합산돼요?',
          '중간에 1,500만 원 넘게 빼면 종합과세돼요?'):
    ck = keys(q)[1]
    ok(ck == [OUT], f'[107] 연금외수령 질문은 그대로 연금외수령 카드: {q} → {ck}')
a = glossary.FAQS[PEN]['lines']
ok(a[0].startswith('연금으로 받은 돈 중') and '골라요' in a[0], '[107] 1,500만 원 카드 첫 줄은 연금수령 선택(전액 종합과세·16.5%)')

# 108 — 재현 입력: 연금계좌를 꾸미는 예금·펀드는 연금계좌 이전(세제 혜택 유지, doc22)
for q in ('다른 은행에서 예금으로 굴리던 IRP를 미래에셋으로 옮길 수 있어요?', '다른 증권사에서 펀드로 운용 중인 연금저축 옮기면 세제 혜택 유지돼요?',
          '다른 은행 예금형 IRP를 미래에셋으로 옮기면 세제 혜택 그대로예요?'):
    fk, ck = keys(q)
    ok(fk == MOVE and MOVE in ck, f'[108] 연금계좌 이전: {q} → {fk} {ck}')
for q in ('다른 은행에서 정기예금으로 넣어 둔 IRP 옮길 수 있어요?', '다른 보험사에서 펀드로 굴린 개인형 IRP 옮기면 손해예요?',
          '다른 은행 펀드형 연금저축 옮기면 세금 있어요?', '다른 증권사에서 ETF로 굴리던 연금저축 미래에셋으로 이전 돼요?',
          '다른 은행에 있는 IRP 예금 그대로 옮길 수 있어요?', '타 증권사 IRP 정기예금 실물이전 돼요?',
          '다른 보험사 연금저축보험을 증권사로 옮기면 혜택 유지돼요?', '연금저축 다른 증권사에서 미래에셋으로 옮길 수 있어요?'):
    ok(MOVE in keys(q)[1], f'[108] 변형도 연금계좌 이전: {q} → {keys(q)}')
ok(any('세제혜택을 유지하면서' in s for _, s in glossary.FAQS[MOVE]['sources']), '[108] 연금계좌 이전 카드 원문: 세제혜택 유지(doc22)')
# 1차에서 고친 것은 그대로 — 연금 아닌 돈을 연금계좌로(도착지 'IRP로·연금저축으로') 옮기는 말과 이직은 연금계좌 이전이 아니다
for q in ('다른 은행 예금을 IRP로 옮기면 세액공제 돼요?', '다른 증권사 주식 팔아서 연금저축으로 옮기면 세액공제 받나요?',
          '다른 은행 예금을 연금저축으로 옮기면 세액공제 돼요?', '다른 증권사에 있는 펀드를 IRP로 옮길 수 있어요?',
          '다른 은행 적금 만기된 돈을 IRP로 옮기면?', '다른 은행에 있는 예금 IRP로 이체하면 공제돼요?', '다른 은행 예금을 IRP 계좌로 옮기면?',
          '다른 은행 통장에 있는 돈 IRP로 옮기면 세액공제 돼요?', '다른 증권사 CMA 잔고를 연금저축으로 옮기면 공제 받나요?',
          '다른 증권사에 있는 ETF 팔아서 연금저축으로 옮기면 세액공제?', '다른 증권사에 있는 달러를 IRP로 옮기면 세액공제 돼요?',
          '다른 회사 퇴직금을 IRP로 옮기면 세액공제 돼요?', '회사 옮기면 퇴직연금을 다른 은행 IRP로 옮겨야 해요?',
          '다른 회사로 이직하면 퇴직연금은 어떻게 옮겨요?', '다른 증권사 ISA 만기 자금을 연금저축으로 옮기면 혜택 있어요?'):
    fk, ck = keys(q)
    ok(fk != MOVE and MOVE not in ck, f'[108] 연금계좌 이전 아님: {q} → {fk} {ck}')
# '금융회사'는 이직이 아니다
ok(MOVE in keys('다른 금융회사로 퇴직연금 옮기면 혜택 그대로예요?')[1], '[108] 금융회사로 옮기는 퇴직연금은 연금계좌 이전')

# 109 — 재현 입력: 계좌의 이점을 묻는 말은 상품 되묻기가 아니다(퇴직금 셋은 '퇴직금 연금 수령 이점' 카드 그대로)
for q in ('퇴직금을 예금 말고 IRP로 받으면 뭐가 좋아요?', '퇴직금을 주식 대신 IRP에 넣으면 뭐가 좋아요?', '퇴직금을 IRP로 받아서 펀드로 굴리면 뭐가 좋아요?'):
    ok(not orchestrator.is_product_ask(q), f'[109] 상품 되묻기 아님: {q}')
    fk, ck = keys(q)
    ok(fk == RET and ck == [RET], f'[109] 퇴직금 연금 수령 이점 카드: {q} → {fk} {ck}')
for q in ('예금 대신 연금저축에 넣으면 뭐가 좋아요?', '주식 계좌 말고 연금저축으로 ETF 사면 뭐가 좋아요?', '연금저축으로 ETF 투자하면 뭐가 좋아요?',
          '주식 대신 연금저축 하면 뭐가 좋아요?', '일반 계좌 말고 IRP에서 펀드 사면 뭐가 좋아요?', '퇴직금 IRP로 받아서 TDF 사면 뭐가 좋아요?',
          '퇴직금 일시금 말고 IRP로 받으면 뭐가 좋아요?', 'ISA 대신 IRP에 넣으면 뭐가 좋아요?', '연금저축펀드로 ETF 사면 뭐가 좋아요?'):
    ok(not orchestrator.is_product_ask(q), f'[109] 계좌의 이점 질문은 상품 되묻기 아님: {q}')
# 1차에서 고친 것은 그대로 — 후보를 두는 말, 상품끼리 견주는 말, 계좌는 자리이고 상품을 두고 묻는 말은 상품 되묻기
for q in ('펀드 중에 사면 뭐가 좋아요?', '미래에셋 펀드 중에 고르면 뭐가 좋아요?', '채권형이랑 주식형 중에 넣으면 뭐가 좋을까요?',
          'TDF랑 예금 중에 IRP에 넣으면 뭐가 좋아요?', '예금이랑 펀드 중 IRP에 넣으면 뭐가 좋아요?', 'IRP에서 TDF랑 ETF 중 사면 뭐가 좋아요?',
          'TDF 대신 예금 넣으면 뭐가 좋아요?', '주식형 펀드 말고 채권형 펀드 넣으면 뭐가 좋아요?', 'ETF 대신 펀드 사면 뭐가 좋아요?',
          'IRP에서 주식형 펀드 말고 채권형 펀드 넣으면 뭐가 좋아요?', '연금저축으로 TDF랑 ETF 중에 사면 뭐가 좋아요?',
          'IRP에서 TDF 사면 뭐가 좋아요?', 'TDF 사면 뭐가 좋아요?', '어느 펀드에 넣으면 뭐가 좋아요?', 'IRP에 어떤 상품 넣으면 뭐가 좋아요?'):
    ok(orchestrator.is_product_ask(q), f'[109] 상품 고르기는 그대로 상품 되묻기: {q}')

# 긴 글에서도 정규식이 느려지지 않는다(돈 낱말·상품 낱말이 수천 번 나와도 1초 안)
for s in ('예금 ' * 1500, '다른 은행 ' + '예금 ' * 1000 + 'IRP로 옮기면', '펀드 IRP로 ' * 700 + '뭐가 좋아요', '1년에 50세 ' * 800 + '빼'):
    t = time.time()
    glossary.cards(s)
    glossary.fixed(s)
    orchestrator.is_product_ask(s)
    ok(time.time() - t < 1.0, f'긴 글 {len(s)}자 처리 {time.time() - t:.2f}초')

# 카드 원문이 extracted/docs 에 그대로 있다(공백 무시)
for k in (PEN, OUT, MOVE, RET):
    for fn, quote in glossary.FAQS[k]['sources']:
        with open(os.path.join(ROOT, 'extracted', 'docs', fn), encoding='utf-8') as fh:
            ok(nows(quote) in nows(fh.read()), f'원문 없음: {k} — {fn} {quote[:30]}')

for m in fail:
    print('실패:', m)
print(f'{n - len(fail)}/{n} 통과')
