def ok(cond, msg):
    global passed, total
    total += 1
    if cond:
        passed += 1
    else:
        print('실패:', msg)


def calc(q):
    return taxcalc.compute(q)


def key(q):
    c = calc(q)
    return [b.get('key_figure') for b in c['blocks']] if c else None


def topics(q):
    c = calc(q)
    return [b['topic'] for b in c['blocks']] if c else None


def figs(q):
    c = calc(q)
    return c['figures'] if c else []


def spans(q):
    p = taxcalc.parse(taxcalc.normalize(taxcalc.norm_ws(q)))
    return [(x['v'], x['role']) for x in p['spans']]


def parsed(q):
    return taxcalc.parse(taxcalc.normalize(taxcalc.norm_ws(q)))


