# -*- coding: utf-8 -*-
"""
③ 질의이해 — 질의 확장.

진단에서 나온 사실: BM25 실패 문항은 질의와 정답의 공통 토큰이 0~1개다.
  "만 72세"        ↔ "70세 이상 80세 미만"
  "암 진단, 병원비" ↔ "요양, 부득이한 사유"
  "전세 보증금"     ↔ "전월세사유, 임차보증금"
  "안 팔고 그대로"  ↔ "실물이전"

고객이 쓰는 말과 문서가 쓰는 말이 다르다. 임베딩이 정답이지만
과제 규정상 임베딩도 HyperCLOVA X 로 붙이는 게 안전하고 지금은 키가 없다.
그래서 규칙 기반 확장으로 BM25 를 어디까지 끌어올릴 수 있는지부터 잰다.
(임베딩을 붙였을 때의 순수 상승분을 보려면 이 기준선이 있어야 한다)
"""
import re

# 고객 표현 → 문서 용어
SYNONYM = [
    # 인출·해지
    (r'안\s*팔고|그대로\s*옮|통째로\s*옮|매도\s*없이', ['실물이전', '실물이전 대상상품']),
    # '55세 이전'·'2013년 이전'의 '이전'(before)은 계좌 이전이 아니다
    (r'옮기|(?<![\d세살년월일])(?<![\d세살년월일]\s)이전(?!에)|갈아타|가져오', ['이전', '이관', '실물이전', '계좌이체']),
    (r'중간에\s*빼|미리\s*빼|꺼내\s*쓰|빼서\s*쓰', ['중도인출', '인출']),
    (r'깨(?:고|면|는)|해지', ['계약해지', '중도해지']),
    # 부득이한 사유
    (r'암|수술|입원|병원비|치료비|요양|아프', ['요양', '부득이한 사유', '6개월 이상 요양', '의료비']),
    (r'전세|보증금|월세|임차', ['전월세', '임차보증금', '주거목적', '전세보증금']),
    (r'집\s*사|주택\s*구입|내\s*집\s*마련', ['무주택자', '주택구입', '주거목적']),
    (r'파산|회생|빚', ['개인회생', '파산선고']),
    (r'재난|수해|지진|화재', ['재난', '천재지변']),
    # 세제
    # "세금은?" 으로 끝나는 질문도 같은 뜻이다. '세금 얼마' 만 잡아서 시연 문장
    # "62살, IRP에서 연 1,800만 원 받으면 세금은?" 이 세제 용어를 하나도 못 받았다.
    # '세금은/이' 를 다 잡으면 세액공제·퇴직소득세 질문에도 연금소득세가 붙어(Q-009·016·025)
    # 묻는 꼴('세금은?')만 넓힌다.
    (r'세금\s*(?:얼마|몇|어느)|세금\s*(?:은|는)?\s*\?|세율|얼마나\s*떼', ['세율', '원천징수', '연금소득세']),
    (r'돌려받|환급|연말정산', ['세액공제', '공제']),
    (r'명퇴|명예퇴직|희망퇴직', ['명예퇴직수당', '퇴직수당', '퇴직소득']),
    (r'한꺼번에\s*받|일시금', ['일시금', '퇴직소득세']),
    (r'나눠\s*받|매달\s*받|다달이', ['연금수령', '연금소득세', '분할수령']),
    # 제도
    (r'회사가\s*(?:돈|부담금)?\s*안\s*(?:넣|내)|미납|밀렸', ['미납', '지연이자', '부담금']),
    (r'월급\s*깎|임금\s*줄|임금피크', ['임금피크제', '임금감소']),
    (r'시간제|알바|아르바이트|파트타임|단시간', ['단시간근로자', '15시간']),
    (r'압류|차압', ['압류', '수급권 보호']),
    # 2000년 이전 가입 개인연금저축 — 문서는 '(구)개인연금저축', '소득공제' 로 쓴다
    (r'(?:19\d{2}|2000)\s*년.{0,30}개인연금|구\s*개인연금', ['(구)개인연금저축', '소득공제', '비과세']),
    # 상품
    (r'안정적|안전한|원금\s*지키|손해\s*보기\s*싫', ['원리금보장', '저위험', '국공채', '채권형']),
    (r'공격적|수익\s*많이|많이\s*불리', ['주식형', '고위험', '위험등급']),
    (r'수수료|보수\s*얼마|비용', ['총보수', '판매보수', '운용보수']),
    (r'창구|지점|영업점', ['판매회사', '오프라인']),
    (r'앱|모바일|온라인', ['온라인', '판매 클래스', 'Class C-e']),
]

# 나이 → 문서의 연령 구간 표현
AGE_BANDS = [
    (55, 70, ['55세 이상 70세 미만', '5.5%']),
    (70, 80, ['70세 이상 80세 미만', '4.4%']),
    (80, 200, ['80세 이상', '3.3%']),
]


# 나이. '세'만 찾다가 "62살"을 놓쳤다(팀 검토 B1). 나이가 둘이면 둘 다 본다
# ("남편 72살 저는 58살"). 뒤에 '전·미만·안 됐' 이 오면 그 나이에 **못 미친** 상황이라
# 구간을 붙이지 않는다 — "55세도 안 됐는데 깨면" 에 55세 이상 세율(5.5%)을 붙여
# 연금소득세 쪽으로 검색을 끌고 간 적이 있다.
# '55세 되기 전에'·'55세가 안 됐는데'도 못 미친 상황이다(수정목록 #2 경계 사례)
_AGE = re.compile(r'(?:만\s*)?(\d{2})\s*(?:세|살)(?!\s*(?:도\s*안|도\s*아직|미만|전|이전|안\s*됐|안\s*되|이하|(?:가|이)\s*(?:안|아직|되기|못)|되기\s*전|넘기\s*전|도\s*못))')
_DECADE = re.compile(r'(\d)0\s*대')

# 금액. "1,800만 원"처럼 띄어 쓰거나 "3천만원"처럼 써도 만원 단위 숫자로 읽는다.
_MONEY = re.compile(r'(\d{1,3}(?:,\d{3})+|\d+)\s*만\s*원|(\d+)\s*천(?:\s*(\d)\s*백)?\s*만\s*원?')
# 한 해 받는 연금액 — 사적연금 1,500만원 분리과세 기준과 비교한다
_YEARLY = re.compile(r'(?:1년|연간?|매년|한\s*해|해마다)\s*(?:에|에만)?\s*$')


def _money_values(q):
    """(만원 단위 값, 바로 앞 6글자) 목록."""
    out = []
    for m in _MONEY.finditer(q):
        if m.group(1):
            v = int(m.group(1).replace(',', ''))
        else:
            v = int(m.group(2)) * 1000 + (int(m.group(3)) * 100 if m.group(3) else 0)
        out.append((v, q[max(0, m.start() - 6):m.start()]))
    return out


def ages(q):
    """질의에 나온 나이(실제로 그 나이인 경우만). 60대 → 60."""
    out = [int(m.group(1)) for m in _AGE.finditer(q)]
    out += [int(m.group(1)) * 10 for m in _DECADE.finditer(q) if m.group(1) in '5678']
    return out


def expand(q):
    """질의에 문서 용어를 덧붙인다. 원문은 그대로 두고 뒤에 붙인다."""
    adds = []
    for pat, words in SYNONYM:
        if re.search(pat, q):
            adds.extend(words)

    for age in ages(q):
        for lo, hi, words in AGE_BANDS:
            if lo <= age < hi:
                adds.extend(words)
                break

    # 금액 → 한도 관련 문서 용어.
    # 예전 규칙은 '1,200만원' 도 1,500만원 기준으로 붙였는데, 1,200만원은 ISA 전환 세액공제
    # 한도라서(Q-015·Q-039) 엉뚱한 용어가 붙었다. 한 해 받는 연금액이 1,000만원 이상일 때만
    # 분리과세 기준을 붙인다(1,200만원을 받는 사람도 기준 근처라 설명이 필요하다).
    if re.search(r'1[,.]?500\s*만\s*원|1천\s*5백\s*만', q):
        adds.append('1,500만원')
    if re.search(r'연금|IRP|수령', q) and any(v >= 1000 and _YEARLY.search(before)
                                           for v, before in _money_values(q)):
        adds.extend(['1,500만원', '분리과세', '종합과세'])
    if re.search(r'퇴직연금|IRP|연금저축|DB|DC', q, re.I):
        adds.append('연금계좌')

    seen, uniq = set(), []
    for a in adds:
        if a not in seen:
            seen.add(a)
            uniq.append(a)
    return (q + ' ' + ' '.join(uniq)).strip(), uniq
