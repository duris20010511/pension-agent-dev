def _ret_won(s):
    """금액 말의 값(만 원) — '5천만 원·3천·1억5천', 말로 하는 '3천'은 3천만 원. 금액이 아니면(맨 숫자 '500'도) None."""
    m = re.fullmatch(r'(?:(\d+(?:\.\d+)?)억)?(?:(\d+(?:\.\d+)?)(천만|백만|천|백|만)?)?원?', re.sub(r'[\s,]', '', s))
    if not m or not (m.group(1) or m.group(3)):
        return None
    v = float(m.group(1) or 0) * 10000
    if m.group(2):
        v += float(m.group(2)) * {'천만': 1000, '천': 1000, '백만': 100, '백': 100, '만': 1, None: 1}[m.group(3)]
    return v


def _jong(ch):
    """한글 음절의 받침 번호(없으면 0, 한글 음절이 아니면 -1) — ㄴ 4·ㄹ 8·ㅆ 20."""
    o = ord(ch) - 0xAC00
    return o % 28 if 0 <= o < 11172 else -1


