# 연금수령 요건 — 1,500만 원을 묻는 질문에서 요건이 안 된다는 말은 연금수령 요건(doc39: 가입 5년·만 55세·한도, doc21: 개시 신청)
# 이야기라 연금외수령이다. 어느 요건인지는 '요건' 바로 앞 이름으로 본다.
# 4차는 허용 목록만 봐서 이름 없는 요건('가입기간이 짧아 요건이·65세이며 요건이·그 요건이')을 놓쳤고(5차 414~416), 5차는 거꾸로
# 제외 목록(공제·소득·감면·과세·사유)만 봐서 모르는 이름을 모두 연금수령 요건으로 읽었다 — '피부양자 요건·기초연금 수급 요건·
# 근로장려금 요건·부양가족 요건·세액공제 혜택 받을 요건'에 연금외수령 카드('1,500만 원을 넘어도 종합과세하지 않아요')가 붙어,
# 연금을 받는 사람에게 틀린 사실을 줬다(6차 510~513). 그래서 셋으로 가른다:
#   다른 제도의 이름이 있으면 아니다 → 연금수령 요건의 이름(연금·수령·개시·가입·기간·나이·계좌·IRP·5년·55세)이 있으면 그렇다
#   → 이름이 없으면(말머리·문장부호·앞 마디 끝 '짧아·65세이며·인데' 뒤, '그·이·해당' 뒤) 그렇다 → 모르는 이름이면 아니다.
# 모르는 이름을 연금수령 요건으로 보지 않는 까닭: '1,500만 원' 카드는 연금외수령이 이 기준과 상관없다는 줄을 함께 싣지만,
# 연금외수령 카드는 연금을 받는 사람에게 그대로 틀린 사실이다.
# '조건'도 같은 뜻으로 쓰지만('가입기간 조건이 안 돼서', 6차 516) 흔한 말이라 이름 없는 '조건'은 연금수령 요건으로 보지 않는다
# 다른 제도 — 공제·소득(연금소득은 연금수령으로 볼 소득이라 뺀다)·감면·과세·사유(4차 310) 요건, 건강보험 피부양자·부양가족, 다른 연금.
# '혜택'은 제도 이름이 아니라서 넣지 않는다 — '세액공제 혜택·세제 혜택'은 공제·세제가 거르고, '연금 수령 혜택 요건'은 연금수령 요건이다(7차 620)
_REQ_OTHER = re.compile(r'공제|(?<!연금)(?<!연금\s)소득|감면|과세|사유|부득이|부양|가족|건강\s*보험|건보|보험료|장려금|수당|세제'
                        r'|(?:기초|국민|주택|공적|유족|장애|노령|사학|군인|공무원|농지|변액|즉시|종신)\s*연금|(?<![A-Za-z])ISA(?![A-Za-z])', re.I)
# 이름 없는 요건 앞 마디가 다른 제도를 말하면('피부양자가 되려면 요건이') 그 제도의 요건이다 — 세금 말(공제·과세)은 연금 이야기에도
# 흔히 붙어서 여기서는 제도 이름만 본다
_REQ_OTHER_SYS = re.compile(r'피부양|부양\s*가족|건강\s*보험|건보|장려금|수당'
                            r'|(?:기초|국민|주택|공적|유족|장애|노령|사학|군인|공무원|농지)\s*연금|(?<![A-Za-z])ISA(?![A-Za-z])', re.I)
# 다만 앞 마디가 그 제도를 이미 받고 있다는 말('국민연금 받는데·받고 있는데·수급 중인데')이면 그 제도의 요건은 이미 갖춘 것이라
# 뒤의 이름 없는 요건은 그 제도 것이 아니다 — 연금계좌 이야기로 본다(7차 619: '국민연금 받는데 요건이 안 돼서 연금저축에서 …')
_REQ_HAVE = re.compile(r'(?:받|타)(?:는데|는\s*중|고\s*있)|(?:받|타)(?:으며|고)(?![가-힣])(?!\s*싶)|(?:수급|수령)\s*중'
                       r'|수급자(?:인데|이고|이며|라서|이라서|로)')
_REQ_PEN = re.compile(r'연금|수령|개시|인출|가입|기간|연수|년수|나이|연령|IRP|아이알피|개인형|계좌|한도'
                      r'|(?<![\d,])\d+\s*(?:년|세|살|개월)', re.I)
# 요건 바로 앞 꾸밈말('받을 수 있는 요건·받기 위한 요건·나이 등 요건')과 가리키는 말·대명사·부사 — 이름이 아니라 건너 본다
_REQ_MOD = frozenset('받을 받는 받은 받기 탈 타는 될 되는 된 되기 할 하는 위한 위해 수 있는 있을 필요한 관련 관련된 같은 등의 등 대한 따른 '
                     '정한 정해진 법적 법정 기본 최소한의'.split())
_REQ_DEMO = frozenset('그 이 저 이런 그런 저런 이러한 그러한 해당 위 위의 앞의 앞서 모든 각종 나 저는 제가 내가 난 전 나는 우리 본인 제 내 '
                      '아직 다 전혀 모두 결국 사실 혹시 만약 근데 그런데 하지만 그래서 그러면 그럼 또'.split())
# 앞 마디가 끝나는 말('짧아·모자라·65세이며·65세인데·받으면·2년이라·돼') — 이 뒤의 요건은 이름이 없다. '감면·해지'는 이름이다
_REQ_CLAUSE_END = re.compile(r'(?:데|지만|며|고|서|니까|니|면|아|어|여|해|돼|라|게|도록|려고|러|야|요|죠|까|다|지)$')
_REQ_PARTICLE = re.compile(r'(?:에서|에게|으로|로|에는|에|의|은|는|이|가|을|를|도|만|과|와|이랑|랑)$')
# 이름 없는 요건 앞 마디의 다른 제도마다 그 제도를 이미 받고 있다는 말이 붙었는지 본다 — '피부양자로 국민연금 받는데 요건이'는
# 받는 건 국민연금이고 피부양자는 그대로 남아, 요건이 피부양자 요건일 수 있다(8차 716). 늘어놓은 이름('국민연금이랑 기초연금
# 받는데')은 뒤 이름의 술어를 함께 쓴다
def _req_other_left(prev):
    ms = list(_REQ_OTHER_SYS.finditer(prev))
    for i, m in enumerate(ms):
        tail = prev[m.end():ms[i + 1].start() if i + 1 < len(ms) else len(prev)]
        if i + 1 < len(ms) and re.fullmatch(r'\s*(?:이랑|랑|과|와|하고|이나|나|및|도|,)?\s*', tail):
            continue
        if not _REQ_HAVE.search(tail):
            return True
    return False


# '○○ 혜택 요건'은 ○○의 혜택을 받는 요건이다 — 혜택 바로 앞 낱말이 연금을 받는 말('연금 수령·연금수령·연금')일 때만 연금수령
# 요건이고, 'IRP 이벤트 혜택·우대금리 혜택·이전 혜택·세금 혜택'은 다른 혜택의 요건이다(8차 717; 7차 620 '연금 수령 혜택 요건'은 그대로)
_REQ_BENEFIT_OWNER = re.compile(r'(?:연금\s*)?수령|연금')


def _req_toks(s):
    return [t for t in (w.strip('\'"‘’“”()[]<>「」『』-~') for w in s.split()) if t]


def _req_clause_end(t):
    base = _REQ_PARTICLE.sub('', t) or t
    return bool(_REQ_CLAUSE_END.search(base)) and not re.search(r'(?:감면|해지|농지|사고|증명서|신청서|확인서|계약서)$', base)


def _req_last_clause(toks):
    """낱말 목록 끝의 마디 — 끝 낱말부터 거슬러 앞 마디 끝 말 바로 뒤까지."""
    out = []
    for t in reversed(toks):
        # '받고 있는데·받고 계신데'의 '…고'는 마디 끝이 아니다(8차 716: '피부양자로 국민연금 받고 있는데'를 '있는데'만 봤다)
        if out and _req_clause_end(t) and not (t.endswith('고') and re.match(r'있|계시|계신|계셔', out[-1])):
            break
        out.append(t)
    return ' '.join(reversed(out))


def _req_is_pension(q, start, word):
    """q[start:]의 '요건'(또는 '조건')이 연금수령 요건을 가리키는가 — 바로 앞 이름(낱말 넷까지)으로 가른다.
    'named' 연금수령 요건 이름이 붙었다, 'bare' 이름 없는 요건이 연금계좌 이야기다, None 아니다·알 수 없다."""
    pre = q[max(0, start - 100):start]          # 앞 이름과 앞 마디만 보면 된다 — 긴 글에서도 한 번에 끝나게
    parts = re.split(r'[?!\n;:]|(?<!\d)[.,]|[.,](?!\d)', pre)     # '1,500만·16.5%'의 쉼표·점은 마디 끝이 아니다
    seg = parts[-1]
    toks = _req_toks(seg)
    name, prev, before = [], None, []
    if toks and re.search(r'[가-힣A-Za-z0-9]$', seg):   # 붙여 쓴 이름('연금수령요건·세액공제요건')
        name.append(toks.pop())
    while toks:
        t = toks.pop()
        if t in _REQ_MOD or t in _REQ_DEMO:
            if name:                            # 이름 앞의 꾸밈 마디('세액공제 받은 IRP 요건')는 이름이 아니다
                break
            continue
        if _req_clause_end(t):
            prev = _req_last_clause(toks + [t])  # 앞 마디 — 이름 없는 요건일 때 어느 제도 이야기인지 본다
            before = toks[:len(toks) + 1 - len(prev.split())]
            break
        name.append(t)
        if len(name) >= 4:
            break
    for i, t in enumerate(name):                 # name 은 요건에 가까운 낱말부터
        if '혜택' in t:
            owner = t[:t.index('혜택')] or (name[i + 1] if i + 1 < len(name) else '')
            if not _REQ_BENEFIT_OWNER.fullmatch(_REQ_PARTICLE.sub('', owner)):
                return None
            break
    txt = ' '.join(name)
    if _REQ_OTHER.search(txt):
        return None
    if _REQ_PEN.search(txt):
        return 'named'
    if name or word != '요건':
        return None                             # 모르는 이름, 이름 없는 '조건' — 연금수령 요건인지 알 수 없다
    if prev is None and len(parts) > 1:         # 말머리·문장부호 바로 뒤의 요건 — 그 앞 마디를 본다
        ptoks = _req_toks(parts[-2])
        prev = _req_last_clause(ptoks)
        before = ptoks[:len(ptoks) - len(prev.split())]
    prev = prev or ''
    # 앞 마디가 다른 제도를 이미 받고 있다는 말뿐이면 그 앞 마디도 본다 — '피부양자인데 국민연금 받는데 요건이'의 요건은
    # 피부양자 요건일 수 있다(8차 716)
    if _req_other_left(prev) or _REQ_OTHER_SYS.search(prev) and _req_other_left(_req_last_clause(before)):
        return None
    return 'bare'


# 연금수령 요건을 지금 못 갖췄다는 말 — 6차까지는 '안·못' 뒤 움직씨 목록만 봐서 '못 지켜·안 들어가·못 넘어·안 나와'를 놓쳤고
# (7차 613~617), 7차는 거꾸로 '요건' 뒤 10자 안의 부정 낱말(안·못·없·않·미달)을 모두 미충족으로 읽어 요건을 갖췄다는 이중 부정
# ('어기지 않았는데·놓치지 않고·문제가 없는데·지장 없고·안 되는 건 아닌데')과 다른 말의 부정('까다롭지 않아서·바뀌지 않았다면·
# 걱정 안 해도·확인은 못 했지만·안 될까 봐 걱정')까지 연금외수령 카드('종합과세하지 않아요')로 보냈다 — 연금을 받는 사람에게 틀린
# 사실이다(8차 714~716). 그래서 부정이 어느 말에 붙었는지 본다. 미충족은 지금 그 요건을 못 갖췄다는 말일 때만:
#   '안·못' + 요건을 갖추는 움직씨(되·채우·갖추·맞·지키·들어가·넘·미치·나오·충족·해당 …), '…지 않·…지 못'의 앞 움직씨가 그 움직씨,
#   '미달·미충족·부족·모자라·벗어나', '해당 없·충족한 적 없'.
# '되·하'는 앞 이름이 요건을 갖추는 말(충족·해당·나이·기간 …)이거나 이름이 없을 때만 — '적용이 안 돼서·문제 안 되는데·걱정 안 해도'는
# 요건이 적용되지 않거나 걱정할 일이 없다는 말이다. '요건(이) 없·요건 없이·상관없이'도 요건이 안 된다는 말이 아니다.
# 부정 뒤가 그 부정을 거두거나('안 되는 건 아니·안 되는 줄 알았') 짐작·걱정('안 될까 봐·안 될지·안 될 수도')이면 아니다.
# 모르는 말은 미충족으로 보지 않는다 — '1,500만 원' 카드는 연금외수령이 이 기준과 상관없다는 줄을 함께 싣지만, 연금외수령 카드는
# 연금수령인 사람에게 그대로 틀린 사실이라 놓치는 쪽이 덜 해롭다.
# 요건의 말이 끝나면('되는데·채웠고·충족해서') 멈춘다 — '요건이 되는데 안 빼면'의 '안'은 다음 마디 말이다
_REQ_MEET_V = re.compile(r'채|찼|차(?![이림])|갖|맞|미치|미쳐|미친|미칠|미달|지키|지켜|지킨|지킬|지켰|들|넘|나오|나와|나온|나올|나왔'
                         r'|충족|만족|해당|구비|성립|부합|통과|도달')
_REQ_DOE = re.compile(r'되|돼|됐|된|될|됨|됩')
_REQ_HAE = re.compile(r'하|해|했|한|할|함|합|시키|시켜|시켰|시킨|시킬')   # '충족 못 시켜서'도
# '안 되·못 하' 앞 이름 가운데 요건을 갖추는 말 — 요건 자체를 가리키는 말('하나가·일부가·중에')과 요건의 잣대(나이·기간·5년)도
# 요건의 수를 세는 말('두 개가·세 가지가·2개가')도 요건 자체를 가리킨다(9차 810)
_REQ_MEET_N = re.compile(r'충족|만족|해당|구비|성립|부합|통과|도달|나이|연령|기간|연수|년수|햇수|하나|일부|몇|전부|^중$'
                         r'|(?<![\d,])\d+\s*(?:년|세|살|개월)|^(?:\d+|한|두|세|네|다섯|여러|몇)?\s*(?:개|가지|항목)$')
_REQ_SHORT = re.compile(r'미달|미충족|불충족|불만족|미비|미흡|부족|모자라|모자란|모자랐|모자람|벗어나|벗어난|벗어났')
_REQ_ADV = frozenset('아직 다 전혀 모두 하나도 제대로 여전히 도저히 끝내 아예 결국 거의 완전히 좀 잘 지금 현재 이제 당장 아직도 조금 약간 '
                     '살짝 딱 영 도무지 계속 그냥 역시 원래 이미 벌써 정말 진짜 사실 아무래도 아쉽게도 불행히도 결국엔'.split())
# 요건과 '안 되' 사이에 끼어도 '되'의 임자가 될 수 없는 말 — 8차까지는 _REQ_ADV 밖의 낱말이 끼면 모두 이름으로 잡아 '요건이 저는
# 안 돼요·제 경우엔 안 돼서·사실상 안 돼서'를 '적용이 안 돼서'처럼 읽었다(9차 810). '적용·문제·걱정'처럼 '되·하'와 짝을 이루는 말은
# 열린 갈래라 거꾸로 '되'와 짝이 될 수 없는 닫힌 갈래만 건너뛴다(모르는 말은 여전히 이름 — 미충족으로 보지 않는다):
#   사람과 그 처지('저는·제가·남편은·저희는·제 경우엔·제 계좌는·우리 부부는·저한테는·저 같은 경우'), 때('이번엔·아직까진·지금으로선·
#   처음부터·애초에'), 꼴로 아는 어찌씨('사실상·서류상·현실적으로·확실히·아쉽게도', '무조건·어차피·절대')
_REQ_WHO = r'저|나|난|전|제|내|저희|우리|본인|남편|아내|와이프|부인|배우자|신랑|엄마|아빠|어머니|아버지|부모님|아들|딸|자녀'
_REQ_WHERE = r'경우|입장|상황|처지|사정|형편|케이스|부부|명의|계좌|통장|연금\s*저축|IRP|아이알피'
_REQ_WHEN = r'이번|지금|현재|당장|올해|금년|요즘|아직|여태|이제|처음|애초|당초|원래|예전|현시점|앞으로|일단|우선|결국'
_REQ_TOPIC = r'(?:는|은|엔|에는|에선|에서는|에서|에|으로선|로선|으로서는|로서는|으로는|로는|으론|론|도|만)'
_REQ_ASIDE = re.compile(     # '나이·제도·전이'는 사람 + 토씨가 아니라 한 낱말이다(나이는 요건의 잣대)
    rf'(?!(?:나이|제도|전이)(?![가-힣]))(?:{_REQ_WHO})(?:는|은|가|이|도|만|한테(?:는|도|선)?|한텐|에게(?:는|도|선)?|에겐|으로선|로선|로서는|의)?'
    rf'|(?:{_REQ_WHERE}){_REQ_TOPIC}|(?:{_REQ_WHEN})(?:{_REQ_TOPIC}|부터|까지(?:는|도)?|까진)?|같은|같이'
    r'|[가-힣]+적으로(?:는|도)?|(?![가-힣]*(?:대상|이상|비정상|현상|보상|손상|인상|예상|상상|진상|최상)$)[가-힣]{2,}상'
    r'|[가-힣]+히|[가-힣]+게도|무조건|어차피|절대|절대로|결코|아마|아마도|솔직히|암튼|아무튼|어쨌든|여하튼', re.I)


def _req_aside(t):
    return bool(_REQ_ASIDE.fullmatch(t))


def _req_strip(t):
    return t.strip('\'"‘’“”()[]<>「」『』-~')


def _req_meet(noun, v, after, obj, word='요건'):
    """부정이 붙은 말 v(앞 이름 noun, 뒤 글 after)가 요건을 갖추는 움직씨인가. obj: 요건 뒤 토씨가 '을·를'.
    '조건'은 흔한 말이라 '조건이 안 나와서'를 조건이 적혀 있지 않다는 뜻으로 더 흔히 써서 '나오'는 '요건'에만 본다."""
    if not v or re.match(r'(?:나와|들어)\s*있', v + after):     # '안 나와 있어서·안 들어 있어서'는 적혀 있지 않다는 말
        return False
    if word != '요건' and v[0] == '나':
        return False
    if v[0] == '들' and obj and not v.startswith('들어가'):      # '요건을 못 들었는데'는 듣지 못했다는 말
        return False
    # 한도는 넘으면 안 되는 위 끝이다(doc39: 연금수령한도 이내) — '한도를 넘지 않았는데·한도를 못 넘어서'는 요건을 지켰다는 말(10차 1016).
    # 아래 끝인 기간·나이('5년을 못 넘겨서')는 그대로 미충족
    if re.match(r'넘|초과', v) and noun and '한도' in noun:
        return False
    if _REQ_MEET_V.match(v):
        return True
    n = noun is not None and bool(_REQ_MEET_N.search(noun) or _REQ_MEET_N.search(_REQ_PARTICLE.sub('', noun)))
    if _REQ_DOE.match(v):
        return noun is None or n
    return bool(_REQ_HAE.match(v) and n)


# 부정한 말을 매인 이름(것·리·일·이유·말 …)으로 받아 다시 부정하는 말 — '안 되는 것도 아니고·안 될 리 없·안 될 일은 없·안 될 이유가
# 없·안 된다는 말은 틀렸·안 될 것 같진 않'은 요건을 갖췄다는 이중 부정이다. 9차까지는 '건·게·거 + 아니'만 봐서 이 꼴을 미충족으로 읽었고,
# 사람·때 말을 건너뛰게 한 9차 810 뒤로 '요건이 저는 안 될 리 없는데'까지 연금외수령 카드로 갔다(10차 1012·1013). 낱말 목록이 아니라
# 꼴(관형형 + 매인 이름 + 없·아니·틀리)로 본다. '안 되는 게 있어서'(있다)·'안 되는 걸 아니까'(알다)·'안 된다는 말을 들었는데'는 아니다
_REQ_DOUBLE_NEG = (r'(?:것|거|게|건|리|일|이유|말|얘기|소리|법|턱|여지|가능성)\s*(?:은|는|이|가|도|만|까지|조차)?\s*'
                   r'(?:(?:전혀|절대|절대로|결코|별로|하나도)\s*)?(?:없|아니(?!까)|아냐|아닌|아녜|아님|틀리|틀렸|틀린|틀려'
                   r'|틀림(?!\s*(?:이\s*)?없))'                      # '안 되는 게 틀림없어서'는 확실히 미충족
                   r'|적\s*(?:은|이|도)?\s*(?:한\s*번도\s*)?없'
                   r'|(?:것|거)\s*(?:같(?:지(?:는|도)?|진)|같다고는|같다곤)\s*(?:않|안)')


def _req_undone(v, after):
    """부정 뒤가 그 부정을 거두거나 짐작·걱정·허락을 묻는 말인가 — '안 되는 건 아니·안 되는 줄 알았·안 되지 않아·안 되진 않아·
    안 될까 봐·안 될지·안 될 수도·안 지켜도 되는지·안 지켜도 돼', 이중 부정(_REQ_DOUBLE_NEG). '…까'는 받침 ㄹ 뒤('될까·채울까')만 —
    '안 되니까'는 까닭을 대는 말이라 미충족이다."""
    m = re.search(r'([가-힣])(?:까|까봐|까바|까요)$', v)
    guess = bool(re.search(r'(?:지|지도|지는|진)$', v) or m and (ord(m.group(1)) - 0xAC00) % 28 == 8)
    return bool(guess or re.search(r'(?:지(?:는|도)?|진)(?:않|못)', v)
                or re.match(r'\S*?\s*(?:(?:건|게|것은?|것이|거는?|거|줄은?)\s*(?:아니|아냐|아닌|알았|알고)'
                            r'|수\s*(?:도|가|는)?\s*(?:있|없)|' + _REQ_DOUBLE_NEG + r')|\S*도\s*(?:되|돼|됐|괜찮|상관)', v + after))


# 못 갖췄다는 말 뒤에 지금은 갖췄다고 다시 말하면('지금까지는 안 됐는데 이제 돼요·처음엔 안 됐는데 지금은 다 채웠어요·안 된다고 들었는데
# 확인해 보니 돼요·해당하진 않는다고 걱정했는데 확인해 보니 해당돼요') 미충족이 아니다(10차 1013·1014·1017). 9차까지는 앞의 부정만 보고
# 연금외수령 카드를 붙였다. 갖췄다는 말은 '이제·지금은·확인해 보니' 같은 바뀜 말 바로 뒤(사이에 '다·요건이'만)의 요건 움직씨로만 본다
# — '안 돼서 이제 연금으로 받으면 돼요'의 '돼요'는 요건 말이 아니고, '지금 해당되는 게 있나요'처럼 꾸미는 꼴(…는·…ㄴ)도 아니다.
# 다른 요건 이야기('나이 요건은 안 되고 가입기간 요건은 이제 채웠어요')로 넘어가면 거기서 멈춘다
_REQ_TURN_CUE = (r'(?:이제(?:는|야|서야)?|지금(?:은|에서야|에야)?|현재(?:는)?|올해(?:는|엔|부터는?)?|이번(?:엔|에는)|요즘(?:은)?|최근(?:엔|에는)?'
                 r'|(?:확인|알아|찾아|다시|살펴|계산|따져|물어)\s*(?:해\s*)?(?:보|봐\s*보)니(?:까)?|알고\s*보니(?:까)?|보니(?:까)?)')
_REQ_TURN_FILL = (r'(?:\s+(?:다|모두|전부|이미|벌써|충분히|드디어|결국|요건(?:이|을|은|도|에)?|조건(?:이|을|은|도)?|그\s*요건(?:이|을|은)?'
                  r'|그\s*조건(?:이|을|은)?|저는|제가|전))*')
_REQ_TURN = re.compile(
    _REQ_TURN_CUE + _REQ_TURN_FILL +
    r'\s+(?P<v>돼|됐|되(?=요|어|었|고|는데|니까|거든|네|더라|죠|지요|더군|나)|될(?=까)|된대|된다|된데|됩니다|됨|채웠|채워(?:졌|져)|채움'
    r'|갖췄|갖춰(?:졌|져)|갖춤|충족(?:해|했|돼|됐|되|함|됨|이에요|이라|입니다)|해당(?:돼|됐|되|해|했|함|됨|이에요|이래요)|맞아|맞췄|맞습니다)'
    r'(?P<tail>\S*)')
# 갖췄다고 끝맺지 않은 꼴 — '이제 돼야·되면·채웠으면·돼도'(바라거나 가정하는 말)는 갖췄다는 말이 아니다
_REQ_TURN_NOT = re.compile(r'(?:야|야지|야겠\S*|도|도록|면|려고|려|게|기)$')
_REQ_TURN_STOP = re.compile(_REQ_TURN_CUE + _REQ_TURN_FILL + r'\s*(?:그\s*)?$')
# 지난 일로 못 갖췄다는 말에 그때를 맞세우는 말('처음엔·작년엔·예전엔 안 됐는데')이 붙고 지금 일을 말하지 않으면 지금 갖췄는지 알 수 없다
# ('전'은 '저는'을 줄인 말과 겹쳐 '전에·전엔'만, '지금까지'는 맞세우는 '는'이 붙을 때만 — '지금까지 못 채웠는데'는 아직 못 갖춘 말)
_REQ_THEN = re.compile(r'(?:(?:처음|예전|작년|재작년|지난\s*해|원래|당시|그때|한때|과거)(?:엔|에는|에|는|은)?'
                       r'|(?:지금|여태)(?:까지는|까진)|전(?:에|엔|에는))(?![가-힣])')
_REQ_PAST_NEG = re.compile(r'(?:됐|되었|채웠|갖췄|맞았|지켰|넘겼|넘었|충족했|충족됐|해당됐|해당했|못\s*했|않았)(?:는데|지만|었는데|다가|고)')


def _req_turned(before, verb, rest):
    """못 갖췄다는 말(before 그 앞 글, verb 부정이 붙은 말, rest 그 뒤 글) 뒤에 지금은 갖췄다고 하면 'met',
    갖췄는지 묻거나('이제 돼요?') 지난 일과 맞세우기만 하면 'maybe', 아니면 None."""
    for c in re.finditer(r'요건|조건', rest):          # 다른 요건 이야기 앞까지만
        if not _REQ_TURN_STOP.search(rest[:c.start()]):
            rest = rest[:c.start()]
            break
    m = _REQ_TURN.search(rest)
    if m:
        nxt = rest[m.end():]
        word = m.group('v') + m.group('tail')
        if re.search(r'(?:지(?:는|도)?|진)$', word) and re.match(r'\s*(?:않|못)', nxt) or re.search(r'(?:지|진)(?:않|못)', word):
            pass                                # '이제 채우지 못해서' — 다시 못 갖췄다는 말
        elif re.search(r'(?:나요|까요|까|는지|는가|가요|을까|건가|건지|거죠|거예요\?|[?？])$', word.rstrip('.!~')) \
                or re.match(r'\s*[?？]', nxt):
            return 'maybe'
        elif not re.search(r'(?:는|은|던|된|될|한|할|운)$', word) and not _REQ_TURN_NOT.search(word.rstrip('.!~')):
            return 'met'                        # '지금 해당되는 게 있나요'의 꾸미는 꼴, '이제 돼야'는 아니다
    if _REQ_THEN.search(before) and _REQ_PAST_NEG.search(verb + rest[:12]):
        return 'maybe'
    return None


def _req_neg_after(q, end, word='요건'):
    """q[end:] 첫머리(10자 안)에 요건(word)을 지금 못 갖췄다는 말이 있으면 True, 그 뒤에 지금은 갖췄는지 알 수 없으면 'maybe'."""
    raw = re.split(r'[?!\n;:]|(?<!\d)[.,]|[.,](?!\d)', q[end:end + 40])[0]
    hit = _req_neg_hit(raw, word)
    if not hit:
        return False
    before, verb, rest = hit
    lead = re.split(r'[?!\n.]', q[max(0, end - len(word) - 20):end - len(word)])[-1]   # '처음엔 요건이 안 됐는데'의 앞말
    turned = _req_turned(lead + ' ' + before, verb, rest + q[end + len(raw):end + len(raw) + 60])
    return True if turned is None else ('maybe' if turned == 'maybe' else False)


def _req_neg_hit(seg, word='요건'):
    """요건 뒤 첫 마디 seg 에서 못 갖췄다는 말 — (요건과 부정 사이 글, 부정이 붙은 말, 그 뒤 글) 또는 None."""
    # '지키지 않아·넘기지 못해'는 한 덩이로 본다('…지'에서 말이 끝나지 않게). '…지는'을 줄인 '…진 않·…진 못'도 같다(9차 809:
    # '해당하진 않아서·채우진 못했어요'를 '…진'에서 끊어 미충족을 놓쳤다). 셈 낱말 '두 가지 못 채워서'의 '가지'와 토씨 '아직까지(까진)
    # 못 채워서'의 '까지'는 움직씨 끝 '…지'가 아니다
    seg = re.sub(r'(?<!\S)(?!(?:\d+\s*)?가지(?:는|도)?\s|\S*까(?:지|진)(?:는|도)?\s)(\S*?(?:지(?:는|도)?|(?<=[가-힣])진))\s+(?=않|못)',
                 r'\1', seg)
    seg = re.sub(r'^(?:을|를|이|가|은|는|도|에|에서|조차)(?=[안못])', r'\g<0> ', seg)   # 띄어 쓰지 않은 '요건을못지켜서·요건이안돼'
    obj = bool(re.match(r'[\'"’”」』)]*\s*(?:을|를)(?![가-힣])', seg))
    toks = [(w.start(), w.end(), _req_strip(w.group())) for w in re.finditer(r'\S+', seg)]
    seen = []                                   # 요건 뒤에 지나온 이름(토씨·부사 말고 다른 말)
    i = 0
    shift = 0                                   # 건너뛴 사람·때·어찌씨의 길이 — 10자는 이름과 술어로만 센다('요건이 제 경우엔 안 돼서')
    while i < len(toks) and toks[i][0] - shift < 10:
        s, e, t = toks[i]
        noun = seen[-1] if seen else None
        if t in ('안', '못') or re.match(r'못(?=[가-힣])|안(?=되|돼|됐|된|될|됨|채|갖|맞|지키|지켜|들어|넘|나와|나오|충족|해당)', t):
            if len(t) == 1:                     # 따로 쓴 '안·못' — 바로 뒤 낱말이 부정이 붙은 말
                if i + 1 >= len(toks):
                    break
                i += 1
                v, after = toks[i][2], seg[toks[i][1]:]
            else:
                v, after = t[1:], seg[e:]
            if _req_meet(noun, v, after, obj, word) and not _req_undone(v, after):
                return seg[:s], v, after
            if _req_clause_end(v):
                break
            i += 1
            continue
        long_ = re.match(r'(.+?)(?:지(?:는|도)?|진)(?:않|못)(.*)$', t)
        if long_:                               # '…지 않·…지 못·…진 않' — 앞 움직씨를 본다
            # 모자란다는 말('미달하·부족하·모자라·벗어나')을 부정하면 요건을 갖췄다는 말이다 — '요건에 미달하지 않아요'(10차 1015)
            if _req_meet(noun, long_.group(1), '', obj, word) and not _REQ_SHORT.match(long_.group(1)) \
                    and not _req_undone(long_.group(2), seg[e:]):
                return seg[:s], t, long_.group(2) + seg[e:]
        elif _REQ_SHORT.search(t):              # '미달·부족' — '미달은 아닌데·부족함 없이'는 아니다
            rest = t[_REQ_SHORT.search(t).end():] + seg[e:]
            if not re.match(r'\S*?\s*(?:(?:은|는|이|가|도|게|건|것은?|것이)\s*)?(?:아니|아냐|아닌|없)', rest) \
                    and not _req_undone(t, seg[e:]):
                return seg[:s], t, seg[e:]
        elif '없' in t and not re.search(r'없(?:지(?:는|도)?|진)(?:않|못)', t):
            # '해당 없·해당 사항 없'과 요건을 갖춘 적이 없다는 말('충족한 적 없·채운 적이 없')만 — '요건(이) 없·문제가 없·지장 없·
            # 걱정은 없·어긴 적 없'은 아니다
            near = [_REQ_PARTICLE.sub('', x) for x in seen[-2:]]
