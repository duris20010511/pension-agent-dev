# '~가 뭐야' 말고 '~ 설명해줘', '~ 뜻 알려줘'도 받는다(짧은 질문만)
_DEFINE = re.compile(r'^\s*(?!그|이거|저거|그거)([가-힣A-Za-z0-9() ·]{2,20}?)\s*(?:이|가|은|는|란|이란)?\s*'
                     r'(?:뭐야|뭔가요|뭐예요|뭐에요|무엇인가요|뭔데|뭐냐|뭐지|무슨\s*뜻(?:이야|이에요|인가요)?|뜻이\s*뭐(?:야|예요)?'
                     r'|(?:뭔지|무슨\s*뜻인지|뜻)?\s*(?:좀\s*)?(?:설명|알려|풀어)\s*(?:해)?\s*(?:줘|주세요|줄래|줄래요|줘요))\s*[?？!.]*\s*$')
_COUNT = re.compile(r'(?:상품|펀드|ETF|종목|디폴트\s*옵션)[^.?!\n]{0,12}몇\s*(?:개|가지|종류)'
                    r'|몇\s*(?:개|가지)[^.?!\n]{0,6}(?:상품|펀드|ETF|종목)', re.I)


def term_of(q):
    """'합성총보수가 뭐야?' → '합성총보수'. 금액·나이 같은 숫자가 있으면 계산 질문이라 None."""
    q = (q or '').strip()
    m = _DEFINE.match(q)
    if not m or re.search(r'\d', q.replace('97.5', '')):
        return None
    head = m.group(1)
    return next((k for k, t in TERMS.items() if re.search(t['match'], head, re.I)), None)


def is_count_ask(q):
    q = q or ''
    return bool(_COUNT.search(q)) and not re.search(r'\d[\d,.]*\s*(?:만|억|천|원|%)', q) and \
        not re.search(r'몇\s*(?:개|가지)[^.?!\n]{0,8}(?:넣|사|담|고르|골라|나눠|분산|투자해|사야)', q)


def fixed(raw):
    """정해진 답 — {'key', 'answer', 'sources', 'actions', 'label'} 또는 None."""
    k = term_of(raw)
    if k:
        t = TERMS[k]
        return {'key': k, 'answer': '\n'.join(t['lines']), 'sources': t['sources'],
                'actions': t['actions'], 'label': f'용어 풀이({k}) — 받은 문서 원문'}
    if is_count_ask(raw):
        return {'key': '상품 수', 'answer': '\n'.join(COUNT_LINES), 'sources': COUNT_SOURCES,
                'actions': COUNT_ACTIONS, 'label': '상품 수 — 문서로 셀 수 있는 것만'}
    return None


def evidence(sources):
    """원문 파일 → 근거 목록. 제도 문서는 doc_meta 제목, 투자설명서는 펀드 이름."""
    ev, seen = [], []
    for f, _ in sources:
        if f in seen:
            continue
        seen.append(f)
        title, as_of, aud = f, '', ''
        try:
            if f.startswith('doc'):
                import doc_meta
                m = doc_meta.meta(f) or {}
                title, as_of, aud = m.get('title') or f, m.get('as_of', ''), m.get('audience', '')
            else:
                import product_names
                name = next((c['name'] for c in product_names.catalog() if c['file'] == f), f)
                title = f'{name} 투자설명서'
        except Exception:
            pass
        ev.append({'n': len(ev) + 1, 'title': f'「{title}」', 'page': '', 'file': f, 'as_of': as_of, 'audience': aud})
    return ev
