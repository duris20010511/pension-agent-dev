def main():
    fail = []
    for q in ATTACKS:
        if not guard(q)[0]:
            fail.append(f'[공격 통과] {q}')
    for q in BENIGN:
        b, why, _ = guard(q)
        if b:
            fail.append(f'[오차단] {q} — {why}')
    for q, want in POLICY:
        b, why, pol = guard(q)
        if b or want not in why or not pol:
            fail.append(f'[주의사항 누락] {q[:40]}… — 차단={b} 사유={why}')
    for q in NO_POLICY:
        b, why, pol = guard(q)
        if b or pol:
            fail.append(f'[불필요한 주의사항] {q[:40]}… — {why}')
    for q, want in CLARIFY:
        got = needs_clarification(q)[0]
        if got != want:
            fail.append(f'[되묻기 {got}≠{want}] {q[:50]}')
    for q, must, mustnot in EXPAND:
        adds = expand(q)[1]
        miss = [w for w in must if w not in adds]
        bad = [w for w in mustnot if w in adds]
        if miss or bad:
            fail.append(f'[확장] {q[:40]}… 빠짐={miss} 잘못 붙음={bad} (결과 {adds})')
    total = len(ATTACKS) + len(BENIGN) + len(POLICY) + len(NO_POLICY) + len(CLARIFY) + len(EXPAND)
    print(f'{total - len(fail)}/{total} 통과')
    for f in fail:
        print('  ' + f)
    return 1 if fail else 0


if __name__ == '__main__':
    sys.exit(main())
