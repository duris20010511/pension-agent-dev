# 계좌 이름 뒤가 아닌 자리의 연도 꼴은 unread_amounts 가 계산기가 뺀 숫자(taxcalc._bare_amounts 의 years)로 같은 규칙을 쓴다(8차 검토 713)
# 2020~2079 뒤에 TDF·빈티지·타겟데이트가 오면 상품 목표 연도다('연금저축 2030 TDF에 넣으면') — 계산기와 같은 말 목록
# (taxcalc._VINTAGE_WORD)으로 되묻지 않는다(9차 검토 801~806)
_THIS_YEAR = datetime.date.today().year
_YEAR_WORD = taxcalc._YEAR_WORD
_YEAR_CTX = (r'(?:' + '|'.join(str(y) for y in range(_THIS_YEAR + 1, 1989, -1)) + r'|\d\d)(?!\d)\s*' + _YEAR_WORD)
_VINTAGE_CTX = r'20[2-7]\d\s*' + taxcalc._VINTAGE_WORD
# 계좌 이름 뒤 단위 없는 숫자('연금저축 600') — 소수('16.5%')·연령대('70대')·연차('3차')·연도는 금액이 아니다(10-14 검토: '16'·'70'을 되물음)
_BARE_AFTER_ACCT = re.compile(r'(?:연금저축|IRP|개인형)\s*(?!' + _YEAR_CTX + r'|' + _VINTAGE_CTX + r')(\d{2,4})'
                              r'(?!\s*(?:만|' + _WON_UNIT + r'|세|살|%|％|년|개|억|천|월|일|대|차|회|번|배|프로|퍼센트|\d|,\d|\.\d))', re.I)


_RULE_LINES = {1500.0, 1200.0, 600.0, 900.0, 1800.0, 5500.0, 4500.0, 300.0}     # 규칙 기준 금액(만 원)
_RULE_LINE_ASK = re.compile(r'(?:1,?500|1,?200|600|900|1,?800|5,?500|4,?500|300)\s*만\s*원?\s*(?:을|이|를|은|이상|이하)?\s*'
                            r'(?:넘|초과|이하|이상|미만|기준|까지|한도|보다)')
# 금액을 내 달라는 말 — 그물은 '세금 계산을 하려는데 금액을 못 읽은' 질문에만 건다. '16.5% 세금 내야 해요?', '한도 900만 원 맞아요?',
# '1,000만 원이면 종합과세 대상이에요?' 같은 규칙 설명·확인 질문은 숫자를 내 달라는 말이 없어 문서 설명으로 간다(10-14 검토 18번)
_CALC_ASK = re.compile(r'얼마|몇\s*(?:십|백|천)?\s*(?:만|억)\s*원?|계산|어떻게\s*(?:돼|되|달라|나와|나오)'
                       r'|(?:세금|세액|공제|공제액|환급액?|수령액|차이)\s*(?:은|는)?\s*(?:\?|$)'
                       r'|비교|(?<![A-Za-z])vs(?![A-Za-z])|어느\s*쪽|뭐가\s*(?:더|나)', re.I)
# 고객이 내놓은 결론을 맞는지 묻는 말('600만 원 넣으면 16.5% 세액공제 맞죠?', '16.5%면 330만 원이죠?') — 되물으면 틀린 전제를
# 굳힌다(평가셋 Q-040 함정: 개인연금저축은 소득공제). 맞는지 문서로 바로잡는 몫이라 그물에 걸지 않는다
_CLAIM_CONFIRM = re.compile(r'맞(?:아요|나요|죠|지요|는지|는\s*(?:거|건)|습니까|을까요|지\s*않|아\s*\?|지\s*\?)'
                            r'|\d[\d,.]*\s*(?:만\s*원|천\s*원|억\s*원?|원|%|％)\s*(?:이|가)?\s*'
                            r'(?:이?죠|인가요|이에요|예요|일까요|이지요)\s*\?')
# 규칙 계산기가 다루지 않는 돈 이야기 — 오래 굴린 효과(과세이연·복리, 평가셋 Q-011 '1억을 25년 굴리면').
# 되물어도 '세액공제 / 연금 받을 때 세금 / 해지 세금' 중 무엇으로도 계산할 수 없다 → 문서(과세이연 표)로 설명한다
_NOT_RULE_CALC = re.compile(r'\d+\s*년\s*(?:정도|동안|간|쯤|이상)?\s*(?:굴리|굴린|굴려|운용|투자|묵혀|묵히|불리|불려)'
                            r'|과세\s*이연\s*(?:효과|차이|덕)|(?:세금을?|세금은)\s*나중에|나중에\s*(?:내|낸|낼|납부)|복리')
# 파서(taxcalc._MONEY)가 금액으로 읽지 못하는 '원' 표기 — '2천원'(천 뒤에 만이 없음), '2000원'·'50000원'(쉼표 없음).
# 읽힌 금액(span)과 겹치지 않을 때만 '못 읽은 금액'이다(10-14 2차 검토 106: '하루 2천원씩'은 금액 목록에 아예 없었다)
# '원' 뒤가 원천·원금·원래 같은 다른 낱말이면 그 '원'은 단위가 아니다(10-14 3차 검토 209: '2025 원천징수영수증'의 '2025 원'을
# 금액으로 읽어 퇴직 갈래 대신 수령 갈래로 갔다) — 규칙은 위 _WON_UNIT
_WON_TEXT = re.compile(r'(?<![\d.,])\d[\d,]*(?:\.\d+)?\s*(?:천|백|십)?\s*' + _WON_UNIT)
# 계산기가 모르는 기간 — 1년·매달만 읽고 나머지는 1년 금액으로 본다. 붙어 있으면 읽은 금액도 믿지 않는다
# '1분기에 300만원'(때)은 기간이 아니다 — 분기·반기는 '마다·별·당'이 붙을 때만.
# '주당'은 한 주(週)일 수도 한 주(株)일 수도 있다 — 기본은 기간으로 보고 되묻는다('IRP에 주당 3만원씩 넣으면'을 1년 3만 원
# 납입으로 읽으면 안 된다, 10-14 4차 검토 308). 앞뒤에 주식·ETF·종목·짜리가 있으면 한 주(株) 값이라 기간이 아니다
# (3차 검토 210: 'ETF 주당 5만원짜리'). 다만 '…씩 넣'이 붙으면 매주 넣는 돈이다
_ODD_PERIOD = (r'(?:하루|매일|날마다|일당|매주|주마다|일주일|한\s*주|격주|(?:\d\s*)?주\s*당|매\s*분기'
               r'|(?:분기|반기|반년)\s*(?:마다|별|당))')
_ODD_PRE = re.compile(_ODD_PERIOD + r'\s*(?:에|마다|당|동안|씩)?\s*(?:약|대략)?\s*$')
_ODD_POST = re.compile(r'\s*(?:을|를)?\s*(?:씩\s*)?' + _ODD_PERIOD + r'(?:\s*(?:마다|에|당))?')
_PER_SHARE = re.compile(r'주\s*당')
_SHARE_CTX = re.compile(r'주식|ETF|종목|짜리|배당', re.I)
# 넣는 말 — taxcalc._IN_VERB 에 적립·저축·모으기를 더한다('매주 5만원씩 적립하면'). '연금저축'의 저축은 계좌 이름이다.
# '모아'는 '모아서 받으면'처럼 받는 말 앞에 와서 뺀다
_IN_WORD = taxcalc._IN_VERB + r'|적립|(?<!연금)(?<!연금 )저축(?!은행|보험)|모으'
_WEEK_IN = re.compile(r'\s*씩\s*(?:더\s*)?(?:' + _IN_WORD + r')')


def _odd_amounts(nq, spans):
    """단위·기간이 낯선 금액 {위치: 고객이 쓴 글} — 파서가 못 읽은 '원' 금액과, 하루·매주처럼 계산기가 모르는 기간이 붙은 금액."""
    def per_share(s, e):
        # 같은 마디 앞뒤에 주식 말이 있고 '…씩 넣'이 붙지 않았으면 '주당'은 한 주(株) 값이다
        clause = re.split(r'[.?!\n,]', nq[:s])[-1] + nq[s:e] + re.split(r'[.?!\n,]', nq[e:])[0]
        return bool(_SHARE_CTX.search(clause)) and not _WEEK_IN.match(nq, e)

    def with_period(s, e):
        # 기간 말을 붙여 보여 준다('하루 2천원', '5만원씩 매주') — 없으면 None
        pre = _ODD_PRE.search(re.split(r'[.?!\n,]', nq[max(0, s - 10):s])[-1])
        post = _ODD_POST.match(nq, e)
        if pre and _PER_SHARE.search(pre.group(0)) and per_share(s, e):
            pre = None
        if post and _PER_SHARE.search(post.group(0)) and per_share(s, e):
            post = None
        if not (pre or post):
            return None
        return nq[s - len(pre.group(0)) if pre else s:post.end() if post else e].strip()
    odd = {}
    for sp in spans:
        if sp['role'] != 'skip':
            t = with_period(sp['s'], sp['e'])
            if t:
                odd[sp['s']] = t
    for m in _WON_TEXT.finditer(nq):
        if not any(m.start() < sp['e'] and sp['s'] < m.end() for sp in spans):
            odd[m.start()] = with_period(m.start(), m.end()) or m.group(0).strip()
    return odd


def unread_amounts(question, calc):
    """계산하려는 세금 질문인데 금액을 읽지 못했으면 [(금액 글, 쓰임)] — 아니면 []."""
    q = question or ''
    # 긴 질문(사연·여러 조건)은 문서로 풀어 설명할 몫이 커서 되묻지 않는다 — 짧은 계산 질문만
    # (평가셋 100문항 중 걸리는 것 0 — 10-14 검토 전에는 Q-040·Q-011이 걸렸다)
    intent = _TAX_INTENT.search(q) or (re.search(r'비교|(?<![A-Za-z])vs(?![A-Za-z])|어느\s*쪽|뭐가\s*(?:더|나)', q, re.I)
                                       and re.search(r'연금저축|IRP|개인형', q, re.I))
    calc_ask, claim = _CALC_ASK.search(q), _CLAIM_CONFIRM.search(q)
    # 결론 확인('… 12만원 맞죠?')도 금액을 묻는 말일 수 있어 여기서는 통과시키고, 아래에서 전제 금액을 다 읽었는지로 가른다
    if len(q) > 90 or not intent or not (calc_ask or claim) or _NOT_RULE_CALC.search(q):
        return []
    blocks = (calc or {}).get('blocks', [])
    if any(b.get('numbers') for b in blocks) or (calc or {}).get('needs'):
        return []                       # 계산했거나, 빠진 값을 되묻는 길이 따로 있다
    p = taxcalc.parse(q)
    # 계산기가 일부러 비켜 가는 상품((구)개인연금저축·보험 연금) — taxcalc._compute 와 같은 조건. 되물어도 계산해 줄 수 없다
    try:
        from understand_guard import old_pension
        old = old_pension(q)
    except Exception:
        old = False
    if p.get('old') or old or (p.get('insure') and not p.get('private')):
        return []
    spans = [s for s in p['spans'] if s['role'] != 'skip']
    # 파서가 못 본 금액·낯선 기간 — 위치는 parse 와 같은 글(normalize → norm_ws) 기준
    odd = _odd_amounts(taxcalc.norm_ws(taxcalc.normalize(q)), p['spans'])
    # 결론 확인 질문은 전제 금액을 다 읽었을 때만 문서 설명으로 보낸다('16.5%면 330만원 맞죠?' — 해지액 2천만 원은 읽었다).
    # 전제를 못 읽었는데 결론 금액('12만원')을 확인해 달라면 모델이 금액을 지어내 맞다/틀리다를 정하게 된다(10-14 2차 검토 106)
    if claim and not (odd and (calc_ask or any(s['role'] is None and s['v'] not in _RULE_LINES for s in spans))):
        return []
    # 규칙의 기준 금액('1,500만 원 넘으면', '900만 원 한도')만 있는 질문은 규칙 설명 질문이다 — 되묻지 않는다
    # (카드 판에서 '1년에 1,500만 원 넘으면 세금이 어떻게 돼요?'를 되물었다)
    nq = taxcalc.normalize(q)
    if spans and not odd and all(s['v'] in _RULE_LINES for s in spans) and _RULE_LINE_ASK.search(nq):
        return []
    unread = [s for s in spans if s['role'] is None]
    bare = _BARE_AFTER_ACCT.findall(taxcalc.normalize(q))
    # 계산기가 연도·빈티지일 수 있어 읽지 않은 숫자도 자리와 상관없이 되묻는다 — 서류에 찍힐 수 있는 해(1990년~내년)에 연도 말이
    # 붙은 것만 연도다. 위 정규식은 계좌 이름 바로 뒤 숫자만 보아 '연금저축에 1900 납입증명서'·'1985 납입증명서 보니 연금저축'은
    # 계산기도(연도로 봄) 그물도(자리가 다름) 놓쳐 되묻지 않고 생성으로 갔다(8차 검토 713)
    # 기간 말(매달·연간·매년…) 바로 뒤 해 꼴은 서류에 찍힐 수 있는 해 + 연도 말이라도 되묻는다 — 그 기간의 금액일 수도 있다
    # ('연간 2024 납입증명서'는 한 해치 증명서일 수도, 연 2,024만 원일 수도 있다. 9차 검토 807). 두 자리는 계산기가 요즘 해(2010년~
    # 내년)를 줄여 쓴 꼴만 담으므로 20xx 로 본다
    yrs, nq2 = [], taxcalc.norm_ws(nq)
    taxcalc._bare_amounts(nq2, [(s['s'], s['e']) for s in p['spans']], None, yrs)
    per = {m.start(1) for m in taxcalc._BARE_PERIOD.finditer(nq2)}
    for raw, s, e in yrs:
        y = int(raw) + (2000 if len(raw) == 2 else 0)
        if not (taxcalc._YEAR_AFTER.match(nq2, e) and 1990 <= y <= _THIS_YEAR + 1 and s not in per) and raw not in bare:
            bare.append(raw)
    if not (unread or bare or odd or (spans and not blocks)):
        return []
    # 재원은 어느 돈인지까지 보여 준다 — '5,000만 원(재원)'은 고객이 알아보기 어렵다
    rows = [(s['s'], taxcalc.won(s['v']), _FUND_NAME.get(s.get('kind')) if s['role'] == 'fund' and s.get('kind') in _FUND_NAME
             else _ROLE_NAME.get(s['role'], '어디에 쓰는 돈인지 확인 필요')) for s in spans if s['s'] not in odd]
    # 낯선 금액은 고객이 쓴 글 그대로 보여 준다 — 어느 금액을 못 읽었는지 알아보게
    rows += [(k, t, '단위·기간 확인 필요') for k, t in odd.items()]
    out = [(t, r) for _, t, r in sorted(rows, key=lambda x: x[0])]
    out += [(f'{b}', '단위(만 원인지) 확인 필요') for b in bare]
    return out


_FUND_NAME = {'retire': '퇴직금', 'free': '세액공제 안 받은 돈', 'credit': '세액공제 받은 돈·수익'}
# 퇴직금·퇴직소득세 질문 — 감면액은 퇴직소득세와 연금 실제 수령 연차로 정해진다(doc39·doc40). 총급여·납입액은 관계없다(10-14 검토 19번)
_RETIRE_Q = re.compile(r'퇴직\s*(?:금|급여|소득)|이연\s*퇴직')
_RETIRE_RULE = ('참고로 연금계좌로 옮긴 퇴직금을 연금수령한도 안에서 연금으로 받으면 원래 퇴직소득세를 1~10년차 30%, '
                '11~20년차 40%, 21년차부터 50% 감면받아요. 한도를 넘긴 몫은 퇴직소득세를 그대로 내요(받은 문서 「연금수령한도 안내」).')
# 퇴직금과 따로 내 돈을 넣는다는 말 — '퇴직금 받은 IRP에 내 돈 500만원 더 넣으면'의 퇴직금은 계좌를 꾸미는 말일 뿐이다
_OWN_MONEY = re.compile(r'납입|(?:내|제|개인|본인|여윳?)\s*돈|따로|별도|말고|(?:추가로?|더)\s*(?:넣|붓)')
# 낯선 금액 뒤의 쓰임 동사 — 넣는 말(_IN_WORD)인지 받거나 꺼내는 말인지. 공제·환급·감면을 '받'는 말은 세금 말이라 뺀다
_ODD_USE = re.compile(r'(' + _IN_WORD + r')|(받|수령|나오|나와|' + taxcalc._OUT_VERB + r')')
# 퇴직소득세 감면을 콕 집어 묻는 말 — '감면', '연금으로 받', '퇴직소득세 … 줄어/아껴'. '세금 얼마나 줄어요'만으로는
# 세액공제로 세금이 주는 것인지 감면인지 가를 수 없다
_RETIRE_RELIEF = re.compile(r'감면|연금\s*(?:으로)?\s*(?:받|수령)'
                            r'|퇴직\s*소득세\s*(?:가|를|은|는|이|도)?\s*(?:얼마나?\s*|좀\s*|더\s*)*(?:줄|아끼|아껴|아낄|덜)')
# 넣는 말 — '적립·저축'도 넣는 말이다(4차 검토 305: '매주 5만원씩 적립하면'). 세액공제 갈래는 공제·환급 말까지 본다
_PAY_VERB = r'넣|납입|붓|부어|부으|적립|(?<!연금)(?<!연금 )저축(?!은행|보험)'
_PAY_ASK = re.compile(r'공제|돌려\s*받|환급|' + _PAY_VERB)
_TAX_RECV = re.compile(taxcalc._DED_RECV + r'(?:' + taxcalc._DED_WORD + r')|(?:공제|환급|감면|혜택|돌려)\s*(?:을|를)?\s*받')


def _odd_use(text, q):
    """낯선 금액(고객이 쓴 글)이 넣는 돈이면 'in', 받거나 꺼내는 돈이면 'out', 쓰임 동사가 없으면 None.
    금액 뒤 같은 마디에서 처음 나오는 쓰임 동사로 가른다 — '매주 5만원 넣으면'은 넣는 돈, '분기마다 300만원씩 받으면'은 받는 돈."""
    nq = taxcalc.norm_ws(taxcalc.normalize(q))     # 낯선 금액 글은 unread_amounts 가 이 글에서 뽑았다
    i = nq.find(text)
    if i < 0:
        return None
    m = _ODD_USE.search(_TAX_RECV.sub(' ', re.split(r'[.?!\n,]', nq[i + len(text):])[0]))
    return None if not m else 'in' if m.group(1) else 'out'


