passed, total = 0, 0


def ok(cond, msg):
    global passed, total
    total += 1
    if cond:
        passed += 1
    else:
        print('실패:', msg)


def n_over(a, calc=None):
    return verify.fix_over1500(a, calc)[1]


# ── 시연 질문 — 규칙 계산이 한도 1,500만 원·인출 2,000만 원을 낸다
