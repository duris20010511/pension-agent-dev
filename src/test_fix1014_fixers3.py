A28 = ('올해 연금수령한도는 1억 원 ÷ (11 − 3) × 120% = **1,500만 원**이에요. 2,000만 원 중 한도를 넘는 초과분 500만 원은 '
       '연금외수령이라 16.5% 기타소득세 82만 5천 원, 한도 안 1,500만 원은 5.5% 연금소득세 82만 5천 원으로 합계 **165만 원**이에요.')
for s in (A28,
          '2,000만 원을 빼면 1,500만 원을 넘는 초과분 500만 원에 16.5%가 붙어요.',          # 한도라는 말이 아예 없어도
          '1,500만 원 초과분(500만 원)만 16.5% 기타소득세예요.',
          '| 1,500만원 | 5.5% | 825,000원 |\n| **초과분** | 500만원 | 16.5% | 825,000원 |'):
    ok(n_over(s, CDEMO) == 0, f'시연 calc 에서 바로잡기 줄: {s[:60]}')
# 재원별 인출 블록('연금수령한도(R-05) = …')에서도 한도 값을 읽는다
CFUND = taxcalc.compute('만 62세예요. IRP 평가액 1억 원 중 퇴직금이 6,000만 원, 세액공제 받은 돈이 4,000만 원이고 '
                        '퇴직소득세 실효세율 5%, 연금수령연차 3년차예요. 올해 2,000만 원 빼면 세금이 얼마예요?')
ok(verify.calc_limits(CFUND) == ([1500.0], 2000.0), f'재원별 calc 의 한도·인출: {verify.calc_limits(CFUND)}')
