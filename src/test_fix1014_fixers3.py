# ── 한도가 1,500만 원이 아닌 계산 — 초과분이 (인출액 − 한도)이면 한도 규칙, 아니면 1,500만 원 규칙 오답은 계속 바로잡는다
C1200 = taxcalc.compute('만 62세, IRP 평가액 8,000만 원, 연금수령연차 3년차예요. 올해 2,000만 원 빼면 세금이 얼마예요?')
C1800 = taxcalc.compute('만 62세, IRP 평가액 1억 2,000만 원, 연금수령연차 3년차예요. 올해 2,000만 원 빼면 세금이 얼마예요?')
ok(verify.calc_limits(C1200) == ([1200.0], 2000.0) and verify.calc_limits(C1800) == ([1800.0], 2000.0),
   f'한도 1,200만·1,800만 calc: {verify.calc_limits(C1200)} {verify.calc_limits(C1800)}')
