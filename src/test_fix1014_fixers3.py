    ok('초과분(**2,000만원 - 1,500만원**)' in t['answer'] and verify.calc_limits(c)[0] == [] and n_over(t['answer'], c) == 1,
       '241: 저장된 115 답(한도 계산 없는 질문)을 calc 와 함께 넘겨도 바로잡아야 함')

