ok(verify.calc_limits(C11)[0] == [] and n_over('1,500만 원 초과분(500만 원)만 추가 세율이 붙어요.', C11) == 1, '한도 없는 calc 는 글자 규칙')
ok(n_over('1,500만 원 초과분(500만 원)만 추가 세율이 붙어요.', None) == 1, 'calc None 은 글자 규칙')

