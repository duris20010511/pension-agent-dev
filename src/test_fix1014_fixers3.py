for idx, s in REPRO.items():
    a, k = verify.fix_over1500(s, CDEMO)
    ok(k == 0 and a == s, f'{idx}: 시연 질문(calc 한도 1,500만)의 맞는 한도 답에 바로잡기 줄 — {s[-60:]!r}')
    ok(n_over(s) == 0, f'{idx}: calc 없이도 답이 밝힌 한도로 가려 그대로여야 함 — {s[-60:]!r}')

