"""10-14 외부 검토 결함(카드 묶음) 13·17·23·24 — 정해진 답(glossary.fixed)과 '검증된 핵심 사실 카드'(glossary.cards),
상품 되묻기(orchestrator.is_product_ask)를 모델 없이 확인한다. python src/test_fix1014_cards.py → 'N/N 통과'."""
import os
import re
import sys

sys.stdout.reconfigure(encoding='utf-8')
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import glossary  # noqa: E402
import orchestrator  # noqa: E402
import product_names  # noqa: E402
import taxcalc  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
n = 0
fail = []


def ok(cond, msg):
    global n
    n += 1
    if not cond:
        fail.append(msg)


def keys(q):
    f = glossary.fixed(q)
    return (f and f['key']), [c['key'] for c in glossary.cards(q)]


def nows(s):
    return re.sub(r'\s+', '', s)


# 13 — 해지·개시 전 인출(연금외수령)에 '1,500만 원 넘으면 종합과세 또는 16.5% 선택' 카드가 붙지 않는다
OUT = '연금외수령과 1,500만 원'
for q in ('IRP 해지할 때 1,500만 원 넘으면 다른 소득이랑 합쳐요?', '연금 개시 전에 1,500만 원 넘게 인출하면 종합과세예요?',
          '1,500만 원 넘게 연금저축에서 빼면 세금 어떻게 돼요?', '연금저축 해지할 때 1,500만 원 넘으면 종합과세돼요?',
          '55세 전에 IRP에서 1,500만 원 넘게 꺼내면 종합과세돼요?', '1,500만 원 넘게 일시금으로 받으면 세금은?'):
    fk, ck = keys(q)
    ok(fk == OUT, f'[13] 정해진 답이 연금외수령 카드: {q} → {fk}')
    ok(ck == [OUT], f'[13] 카드는 연금외수령 하나(1,500만 원 카드 없음): {q} → {ck}')
a = '\n'.join(glossary.FAQS[OUT]['lines'])
ok('무조건 분리과세' in a and '기타소득세 16.5%' in a and '종합과세와 고를 수 없어요' in a, '[13] 연금외수령 카드: 기타소득 무조건 분리과세')
ok(a.splitlines()[0].startswith('해지하거나 연금 개시 전에 빼는 돈') and '골라요' not in a.splitlines()[0], '[13] 첫 줄이 연금외수령 답')
ok('연금수령' in a and '16.5% 분리과세 중에서 고르는 건' in a, '[13] 1,500만 원 선택은 연금수령 이야기라고 구분')
# 연금으로 받는 1,500만 원 질문은 그대로 '1,500만 원'
for q in ('연금 받을 때 1년에 1,500만 원 넘으면 세금이 어떻게 돼요?', 'IRP에서 연금으로 1,500만 원 넘게 받으면 종합과세돼요?',
          '연금 수령 중에 1,500만 원 넘게 인출하면 세금은?', '연금 개시 후에 1,500만 원 넘게 빼면 어떻게 돼요?',
          '연금소득 1,500만 원 넘으면 종합과세예요?', '퇴직금은 1,500만 원 넘어도 괜찮아요?'):
    fk, ck = keys(q)
    ok(fk == '1,500만 원' and ck == ['1,500만 원'], f'[13] 연금수령 1,500만 원 질문은 그대로: {q} → {fk} {ck}')
a = '\n'.join(glossary.FAQS['1,500만 원']['lines'])
ok('넘은 부분만이 아니라' in a and '전액' in a and '금액과 상관없이 분리과세' in a, '[13] 1,500만 원 카드: 전액 + 연금외수령 구분 줄')

# 17 — 이직·예금·주식·ISA 자금을 옮기는 말에 '연금계좌는 금융회사끼리 옮길 수 있어요' 카드가 붙지 않는다
for q in ('다른 은행 예금을 IRP로 옮기면 세액공제 돼요?', '다른 회사로 이직하면 퇴직연금은 어떻게 옮겨요?',
          '다른 회사로 옮기면 DC 퇴직연금은 어떻게 돼요?', '다른 증권사 ISA 만기 자금을 연금저축으로 옮기면 혜택 있어요?',
          '다른 증권사 주식 팔아서 연금저축으로 옮기면 세액공제 받나요?'):
    fk, ck = keys(q)
    ok(fk != '연금계좌 이전' and '연금계좌 이전' not in ck, f'[17] 연금계좌 이전 아님: {q} → {fk} {ck}')
# 연금계좌를 옮기는 질문은 그대로(연금 낱말 뒤의 '예금'·'다른 회사 IRP' 포함)
for q in ('연금저축을 다른 증권사에서 미래에셋으로 옮길 수 있어요?', 'IRP를 다른 은행으로 옮길 수 있나요?',
          '다른 증권사 IRP를 미래에셋으로 옮기려면 어떻게 해요?', '타 증권사에서 IRP로 옮기려면 어떻게 해요?',
          'IRP에 든 정기예금을 다른 증권사로 옮길 수 있어요?', '다른 금융회사로 퇴직연금 옮기면 혜택 그대로예요?',
          '다른 증권사 연금저축펀드를 미래에셋으로 옮기면 세제 혜택 그대로예요?', '다른 회사 IRP를 미래에셋으로 이전할 수 있어요?'):
    fk, ck = keys(q)
    ok(fk == '연금계좌 이전' and '연금계좌 이전' in ck, f'[17] 연금계좌 이전은 그대로: {q} → {fk} {ck}')
ok(glossary.fixed('다른 회사로 이직하면 퇴직금 옮겨야 해?') is None, '[17] 이직 퇴직금은 정해진 답 아님(test_rules 기준)')

# 23 — 상품을 골라 달라는 말은 상품 되묻기(적합성 진단)로, TDF 정의 카드가 붙지 않는다
for q in ('TDF 어떤 거 가입할까요?', 'TDF 뭐 하나 들어볼까요?', '펀드 중에 사면 뭐가 좋아요?', '미래에셋 펀드 중에 고르면 뭐가 좋아요?',
          '채권형이랑 주식형 중에 넣으면 뭐가 좋을까요?', 'TDF랑 예금 중에 IRP에 넣으면 뭐가 좋아요?'):
    ok(orchestrator.is_product_ask(q), f'[23] 상품 되묻기: {q}')
    ok(not taxcalc.compute(q) and not any(len(m['names']) == 1 for m in product_names.resolve(q)),
       f'[23] 계산 블록·상품 하나 지목 없음(되묻기 길로 감): {q}')
    fk, ck = keys(q)
    ok(fk != 'TDF 뜻' and 'TDF 뜻' not in ck, f'[23] TDF 정의 카드 아님: {q} → {fk} {ck}')
# 제도 이점·정의 질문은 그대로
for q in ('퇴직금을 IRP로 받으면 뭐가 좋아요?', 'IRP에 넣으면 뭐가 좋아요?', '연금저축 가입하면 뭐가 좋아요?',
          'ISA 만기 자금을 연금계좌로 옮기면 뭐가 좋아요?', 'TDF에 뭐가 들어 있어요?', 'TDF가 뭐예요?', 'TDF는 어떤 거예요?'):
    ok(not orchestrator.is_product_ask(q), f'[23] 상품 되묻기 아님: {q}')
for q in ('TDF가 뭐예요?', 'TDF는 어떤 거예요?', 'TDF 설명해줘', 'TDF란?', 'TDF는 뭐 하는 펀드예요?'):
    ok(glossary.fixed(q) and glossary.fixed(q)['key'] == 'TDF 뜻', f'[23] TDF 정의는 그대로: {q}')
for q in ('연금 상품 뭐가 좋아?', '제일 좋은 연금 상품 골라 주세요', 'ETF 뭐 사면 돼요?', 'IRP에 펀드 뭘 넣어야 해요?'):
    ok(orchestrator.is_product_ask(q), f'[23] 상품 질문은 그대로: {q}')

# 24 — 연금저축·ISA 위험자산 한도에 퇴직연금 70% 카드가 붙지 않고, '문서에 없다' 카드가 붙는다
RA = '연금저축·ISA 위험자산 한도'
for q in ('연금저축 위험자산 한도는 얼마예요?', 'ISA 위험자산 비중 제한 있어요?', '연금저축 1,500만 원 넣으면 위험자산 몇 %까지 돼요?',
          '연금저축은 위험자산 한도가 얼마예요?', '연금저축펀드는 위험자산 비중 제한 없어요?'):
    fk, ck = keys(q)
    ok(fk == RA and ck == [RA], f'[24] 연금저축·ISA 카드만: {q} → {fk} {ck}')
a = '\n'.join(glossary.FAQS[RA]['lines'])
ok('적혀 있지 않아요' in a and '퇴직연금 규칙' in a and not re.search(r'연금저축[^\n]{0,20}70%', a), '[24] 문서에 없다 + 70%는 퇴직연금')
for q in ('IRP에서 위험자산은 얼마까지 살 수 있어요?', 'DC 위험자산 한도 몇 %예요?', '퇴직연금 위험자산 한도는?', '위험자산 한도는 얼마예요?'):
    fk, ck = keys(q)
    ok(fk == '위험자산 한도' and ck == ['위험자산 한도'], f'[24] 퇴직연금 위험자산은 그대로: {q} → {fk} {ck}')
fk, ck = keys('IRP랑 연금저축 위험자산 한도 차이가 뭐예요?')
ok(fk == '위험자산 한도' and ck == ['위험자산 한도', RA], f'[24] 둘 다 물으면 두 카드: {fk} {ck}')
ok('연금저축·ISA의 위험자산 비율 한도는 받은 문서에 없어요' in '\n'.join(glossary.FAQS['위험자산 한도']['lines']), '[24] 70% 카드에 구분 줄')

