def n_fix(a, calc=None):
    out, k = verify.fix_over1500(a, calc)
    if k:
        assert out.endswith(verify.OVER1500_NOTE) and out.count(verify.OVER1500_NOTE) == 1
    else:
        assert out == a
    return k


