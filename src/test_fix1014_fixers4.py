# -*- coding: utf-8 -*-
"""
10-14 4차 검토 — fixers4 묶음(verify.fix_over1500 의 '초과분' 규칙 가르기) 회귀 시험. API 호출 없음.

    python src/test_fix1014_fixers4.py

3차 고침은 규칙 계산(calc)의 연금수령한도가 1,500만 원이면 통째로 건너뛰었고(314·315), 초과액이 마침 1,500만 원이면
'1,500만 원을 넘으면'의 1,500만을 초과액으로 셌으며(316), '사적연금 인출 한도'처럼 한도 규칙 말이 낀 한도를 1,500만 원 기준으로
봤다(317). 이제
  - 한도 1,500만 calc 에서도 건너뛰지 않는다 — 이름 없는 1,500만은 그 한도로 보되, 초과분에 종합과세·분리과세를 붙였거나
    연금소득·분리과세 같은 1,500만 원 규칙 말로 기준을 부른 문장은 바로잡는다(doc38 10행: 1,500만 원은 전 금융기관 합산).
  - 초과분 뒤에 종합과세·분리과세가 오면 초과액 대조·'한도 바로 뒤' 판정보다 먼저 1,500만 원 규칙으로 본다.
  - 초과액 대조에서 기준으로 쓴 금액('1,500만 원을 넘')과 뺄셈의 두 항은 초과액으로 세지 않는다.
  - '인출·올해·계좌'가 낀 한도는 연금수령한도다(doc37 '인출 한도', doc2 '올해 한도', doc22 '해당계좌의 연금수령한도').
"""
import json
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
sys.stdout.reconfigure(encoding='utf-8')

import taxcalc
import verify

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
passed, total = 0, 0


def ok(cond, msg):
    global passed, total
    total += 1
    if cond:
        passed += 1
    else:
        print('실패:', msg)


def fixed(a, calc=None):
    """바로잡기 줄이 한 번 붙었는가."""
    out, k = verify.fix_over1500(a, calc)
    return k == 1 and out.endswith(verify.OVER1500_NOTE) and out.count(verify.OVER1500_NOTE) == 1


def kept(a, calc=None):
    out, k = verify.fix_over1500(a, calc)
    return k == 0 and out == a


QDEMO = '만 62세, IRP 평가액 1억 원, 연금수령연차 3년차예요. 올해 2,000만 원 빼면 세금이 얼마예요?'
CDEMO = taxcalc.compute(QDEMO)
ok(verify.calc_limits(CDEMO) == ([1500.0], 2000.0), f'시연 질문 calc 의 한도·인출: {verify.calc_limits(CDEMO)}')

# ── 314 — 한도 1,500만 calc 라도 1,500만 원 규칙 문장은 바로잡는다
S314 = ['연금소득이 1년에 1,500만 원을 넘으면 초과분은 종합과세 또는 16.5% 분리과세예요.',
        '연금소득이 1,500만 원을 넘으면 초과분만 16.5% 분리과세예요.',
        '사적연금소득이 연 1,500만 원을 넘으면 초과분만 종합과세돼요.',
        '분리과세 한도 1,500만 원을 넘으면 초과분은 16.5%예요.',
        '연금소득 1,500만 원 초과분은 종합과세 대상이에요.']
R240 = ['분리과세 가능 한도 1,500만 원을 넘으면 초과분은 16.5%예요.',
        '연금소득 연간 한도 1,500만 원을 넘으면 초과분은 16.5%예요.',
        '저율과세 한도 1,500만 원을 넘으면 초과분은 16.5%예요.',
        '사적연금 한도 1,500만 원을 넘으면 초과분만 16.5%예요.',
        '분리과세 적용 한도(연 1,500만 원)를 넘는 초과분은 16.5%예요.',
        '종합과세 기준 한도 1,500만 원을 넘으면 초과분은 16.5%예요.']
for s in S314 + R240:
    ok(fixed(s, CDEMO), f'314: 시연 calc(한도 1,500만)에서 1,500만 원 규칙 문장을 놓침 — {s}')
    ok(fixed(s), f'314: calc 없이도 바로잡아야 함 — {s}')
# 시연 답 뒤에 '참고로 …'로 붙여도
A28 = ('올해 연금수령한도는 1억 원 ÷ (11 − 3) × 120% = **1,500만 원**이에요. 2,000만 원 중 한도를 넘는 초과분 500만 원은 '
       '연금외수령이라 16.5% 기타소득세 82만 5천 원, 한도 안 1,500만 원은 5.5% 연금소득세 82만 5천 원으로 합계 **165만 원**이에요.')
ok(kept(A28, CDEMO), '314: 시연 답 자체에 바로잡기 줄')
ok(fixed(A28 + '\n\n참고로 ' + S314[0], CDEMO), "314: 시연 답 뒤 '참고로 …' 1,500만 원 규칙 문장을 놓침")
# '1,500만원 한도 초과분 … 종합과세 또는 16.5% 선택'은 한도 바로 뒤라도 1,500만 원 규칙(저장된 답 _gen_calcx_r2)
S_LIMCOMP = '세액공제 받은 금액+운용수익 1,800만원 중 **1,500만원 한도 초과분 300만원**에 대해 종합과세 또는 16.5% 선택 가능'
ok(fixed(S_LIMCOMP, CDEMO) and fixed(S_LIMCOMP), '314: 한도 초과분에 종합과세·16.5% 선택을 붙인 문장')
# 한도 규칙 문장은 계속 그대로 — 한도가 1,500만 원이라 이름 없는 1,500만은 그 한도다
for s in ('1,500만 원을 넘는 초과분은 16.5% 기타소득세예요.',
          '연금수령한도 1,500만 원을 넘는 초과분은 16.5% 기타소득세예요.',
          '2,000만 원을 빼면 1,500만 원을 넘는 초과분 500만 원에 16.5% 기타소득세가 붙어요.',
          '1,500만 원 초과분(500만 원)만 16.5% 기타소득세예요.',
          '2,000만 원 − 1,500만 원 = 초과분 500만 원은 16.5% 기타소득세예요.',
          '연금수령한도는 1,500만 원이에요.\n- 초과분(2,000만 원 − 1,500만 원 = 500만 원)은 16.5% 기타소득세예요.',
          '| 연금수령한도 | 1,500만원 |\n| 초과분 | 500만원 | 16.5% 기타소득세 |'):
    ok(kept(s, CDEMO), f'314: 시연 calc 의 맞는 한도 문장에 바로잡기 줄 — {s[:60]}')
# doc22 '연금수령한도 外 → 기타소득세16.5%(분리과세)' — 기타소득세에 붙은 (분리과세)는 과세 방식 선택이 아니다
S_DOC22 = '연금수령한도 1,500만 원을 넘는 초과분 500만 원은 연금외수령이라 기타소득세 16.5%(분리과세)예요.'
ok(kept(S_DOC22, CDEMO) and kept(S_DOC22), '기타소득세 16.5%(분리과세) 한도 문장에 바로잡기 줄')

# ── 315 — 한도 1,500만 calc 의 다른 인출액(초과분 없음·3,000만)·나이 없는 질문
for q in ('IRP 평가액 1억 원, 연금수령연차 3년차, 올해 1,500만 원 빼면 세금이 얼마예요?',
          '만 62세, IRP 평가액 1억 원, 연금수령연차 3년차예요. 올해 3,000만 원 빼면 세금이 얼마예요?',
          'IRP 평가액 1억 원, 연금수령연차 3년차예요. 올해 2,000만 원 빼면 세금이 얼마예요?'):
    c = taxcalc.compute(q)
    ok(verify.calc_limits(c)[0] == [1500.0], f'315: 한도 1,500만 calc 가 아님 — {q} {verify.calc_limits(c)}')
    ok(fixed(S314[0], c), f'315: 한도 1,500만 calc 에서 1,500만 원 규칙 문장을 놓침 — {q}')

# ── 316 — 초과액(인출 − 한도)이 마침 1,500만 원인 calc
C1227 = taxcalc.compute('만 62세, IRP 평가액 8,000만 원, 연금수령연차 3년차예요. 올해 2,700만 원 빼면 세금이 얼마예요?')
C1833 = taxcalc.compute('만 62세, IRP 평가액 1억 2,000만 원, 연금수령연차 3년차예요. 올해 3,300만 원 빼면 세금이 얼마예요?')
ok(verify.calc_limits(C1227) == ([1200.0], 2700.0) and verify.calc_limits(C1833) == ([1800.0], 3300.0),
   f'316: calc 한도·인출 {verify.calc_limits(C1227)} {verify.calc_limits(C1833)}')
for c, name in ((C1227, '1,200/2,700'), (C1833, '1,800/3,300')):
    for s in (S314[0], '1,500만 원을 넘는 초과분은 16.5% 기타소득세예요.', '1,500만 원 초과분만 16.5%예요.',
              '300만 원(1,100만 - 1,500만)이 1,500만 원 초과분임.'):        # 뺄셈의 항 1,500만은 초과액이 아니다
        ok(fixed(s, c), f'316: calc {name} 에서 1,500만 원 규칙 문장을 놓침 — {s}')
# 초과액 1,500만 원을 그대로 밝힌 한도 규칙 문장은 그대로
for s in ('연 1,500만 원 이하라 분리과세 얘기는 해당 없어요. 2,700만 원을 빼면 초과분 1,500만 원은 16.5% 기타소득세예요.',
          '연 1,500만 원 이하라 분리과세 얘기는 해당 없어요. 초과분(2,700만 원 − 1,200만 원)은 16.5% 기타소득세예요.'):
    ok(kept(s, C1227), f'316: 초과액을 밝힌 한도 규칙 문장에 바로잡기 줄 — {s}')

# ── 317 — '인출·올해·계좌'가 낀 한도는 연금수령한도(doc37·doc2·doc22) — 초과분 16.5% 기타소득세는 한도 규칙
S317 = ['사적연금 인출 한도 1,500만 원을 넘는 초과분 500만 원은 16.5% 기타소득세예요.',
        '사적연금 계좌의 인출 한도 1,500만 원을 넘는 초과분 500만 원은 16.5% 기타소득세예요.',
        '사적연금 올해 한도 1,500만 원을 넘는 초과분 500만 원은 16.5% 기타소득세예요.',
        '사적연금 계좌 한도 1,500만 원을 넘는 초과분 500만 원은 16.5% 기타소득세예요.',
        '연금소득 연간 인출 한도 1,500만 원을 넘는 초과분 500만 원은 16.5% 기타소득세예요.',
        '분리과세 계좌 인출 한도 1,500만 원 초과분 500만 원은 16.5% 기타소득세예요.']
for s in S317:
    ok(kept(s), f'317: 연금수령한도 문장에 바로잡기 줄 — {s}')
    ok(kept(s, CDEMO), f'317: 시연 calc 에서도 그대로여야 함 — {s}')
for s, k in (('사적연금 인출 한도', 'L'), ('사적연금 계좌의 인출 한도', 'L'), ('사적연금 올해 한도', 'L'), ('사적연금 계좌 한도', 'L'),
             ('연금소득 연간 인출 한도', 'L'), ('분리과세 계좌 인출 한도', 'L'),
             ('사적연금 한도', 'R'), ('사적연금 연간 한도', 'R'), ('분리과세 가능 한도', 'R')):
    ok(verify._basis_kinds(s)[-1][1] == k, f"317: '{s}'의 한도 종류가 {k} 가 아님: {verify._basis_kinds(s)}")
# 인출 한도라 불러도 초과분에 종합과세·분리과세를 붙이면 1,500만 원 규칙
ok(fixed('사적연금 인출 한도 1,500만 원을 넘는 초과분은 종합과세 또는 16.5% 분리과세예요.'), '317: 인출 한도 + 종합과세 문장을 놓침')

