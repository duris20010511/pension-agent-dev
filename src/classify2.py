# -*- coding: utf-8 -*-
"""
③ 유형 분류 — 개선판.

기존 understand_guard.classify() 는 유형별 키워드 개수를 세서 최다 득표를 고른다.
그 결과 100문항 중 39개만 맞았고, 오분류가 '제도'로 쏠렸다:
    조건부추천 → 제도  8건
    상품비교   → 제도  6건
    절차      → 제도  5건
원인: '제도' 힌트에 DB/DC/IRP/퇴직연금이 들어 있는데 이 단어는 거의 모든 질의에 나온다.
주제어를 세는 방식은 '무엇에 대한 질문인가'는 잡아도 '무엇을 요구하는가'를 못 잡는다.

이 분류가 중요한 이유: prompts.py 의 유형별 프라이어가 이 결과를 보고 프롬프트를 고른다.
분류가 틀리면 엉뚱한 프라이어가 주입된다. 실측으로 분류 정답 문항 84.5% vs 오답 문항 75.5%.

개선 방향: **의도 신호를 주제어보다 먼저 본다.**
"추천해 주세요"는 DB 를 언급하든 말든 조건부추천이다.
"뭐가 달라요"는 비교다. "어떻게 신청해요"는 절차다.
제도는 다른 신호가 없을 때의 기본값으로 내린다.
"""
import re

# 우선순위 순서대로 검사한다. 먼저 걸리는 것이 이긴다.
RULES = [
    # ── 의도 신호 (주제와 무관하게 강하다) ──────────────────────────
    ('조건부추천', [
        r'추천', r'골라\s*주', r'뽑아\s*주', r'찍어\s*주', r'딱\s*하나',
        r'뭐가\s*(?:제일|가장)\s*(?:좋|나은|괜찮)', r'어떤\s*(?:걸|것|상품)\s*(?:살|사|담|넣)',
        r'몰아\s*넣', r'전부\s*(?:거기|여기)', r'이거\s*(?:사면|들어가면)\s*되',
        r'설명은?\s*됐', r'상품명만',
    ]),
    ('상품비교', [
        r'뭐가\s*다르', r'뭐가\s*달라', r'차이\s*(?:가|는|점)', r'비교',
        r'어느\s*(?:쪽|것|게)\s*(?:더|나은)', r'대신\s*(?:에|넣|사)',
        r'[\w가-힣]+이?랑\s*[\w가-힣]+\s*(?:중|둘)', r'(?:A|B)\s*(?:랑|와|과)\s*',
    ]),
    ('절차', [
        r'어떻게\s*(?:신청|하면|받|옮기|바꾸|해지|인출)', r'절차', r'서류',
        r'뭐뭐\s*(?:챙기|가져)', r'어디(?:서|로)\s*(?:가|신청|해)', r'준비물',
        r'며칠', r'얼마나\s*걸리', r'방문해야', r'온라인으로\s*(?:되|가능)',
    ]),
    # ── 주제 신호 ────────────────────────────────────────────────
    ('세제', [
        r'세액공제', r'소득공제', r'연금소득세', r'퇴직소득세', r'기타소득세',
        r'종합과세', r'분리과세', r'과세이연', r'비과세', r'원천징수',
        r'세금\s*(?:얼마|몇|어떻게|떼|내)', r'절세', r'연말정산', r'세율',
        r'수령한도', r'수령연차', r'환급',
    ]),
    ('상품설명', [
        r'위험등급', r'총보수', r'보수\s*(?:가|는|얼마)', r'수수료\s*(?:가|는|얼마)',
        r'클래스', r'설정액', r'수익률', r'변동성', r'비교지수', r'벤치마크',
        r'무슨?\s*펀드', r'어디다\s*(?:굴리|투자)', r'뭘\s*담(?:는|고)',
    ]),
    ('제도', [
        r'가입\s*(?:대상|조건|자격)', r'규약', r'제도\s*변경', r'평균임금',
        r'계속근로', r'압류', r'지연이자', r'가입자\s*교육', r'실물이전',
        r'중도인출\s*(?:사유|요건|가능)', r'근로자대표', r'과태료',
    ]),
]

# 펀드를 특정해 부르는 신호 — 있으면 상품 계열로 본다
FUND_HINT = re.compile(
    r'(?:솔로몬|라이프사이클|퇴직플랜|필승코리아|목표전환|전단채|거북이|파워인덱스|'
    r'고배당|인덱스플러스|초단기|국공채|회사채|TDF|ETF)'
    r'|[A-Z]{2,}\d{3,}'
    r'|\d{4}(?=\s*(?:이랑|랑|과|와|하고|,))'
)

MULTI = re.compile(r'(?:이랑|랑|과|와|하고|,)\s*[가-힣A-Za-z0-9]{2,}')


def classify(question):
    q = question or ''
    for cat, pats in RULES:
        for p in pats:
            if re.search(p, q):
                # 상품 신호가 함께 있으면 제도/세제 대신 상품 계열로 올린다
                if cat in ('제도', '세제') and FUND_HINT.search(q):
                    return '상품비교' if len(MULTI.findall(q)) >= 1 else '상품설명'
                return cat
    # 아무 신호도 없을 때
    if FUND_HINT.search(q):
        return '상품비교' if len(MULTI.findall(q)) >= 1 else '상품설명'
    # 여러 제도가 얽힌 정황이면 종합
    n_sys = len(set(re.findall(r'DB|DC|IRP|연금저축|퇴직금|ISA', q, re.I)))
    if n_sys >= 2:
        return '종합'
    return '제도'
