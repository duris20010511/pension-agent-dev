    d = cc.compare(p, A(('600', 600, '납입', '매달')))
    ok(d and d[0][3] == '기간', f'q 없이 모델 기간을 버림 {d}')

    # 11) 주인 — 다른 사람 돈이면 정규식이 납입 계산에서 뺐어도 되묻는다. 계산 블록에 뺐다는 말이 없어 '둘이 합쳐·각자'에
    # 본인 몫만 답처럼 놓였다(10-15 검증 회귀: '남편은 IRP에 900, 저는 연금저축에 600 … 둘이 합쳐' → 99만 원)
    for q in ('남편은 IRP에 900 넣었고 저는 연금저축에 600 넣었어요. 제 총급여 5천이면 제 공제 얼마?',
              '남편은 IRP에 900, 저는 연금저축에 600 넣었는데 둘이 합쳐 세액공제 얼마 받아요? 제 총급여 5천'):
        sp = [('900', 900, 'contrib', None, 'person'), ('600', 600, 'contrib', None, 'private'), ('총급여 5천', 5000, 'income')]
        ext = A(('900', 900, '납입', '모름', '다른사람'), ('600', 600, '납입', '모름', '본인'))
        d = cc.compare(P(q, sp, contrib=[{'v': 600.0}]), ext, q=q)
        ok(d and d[0][3] == '주인', f'정규식이 뺀 남의 돈을 되묻지 않음 {q} {d}')
        d = cc.compare(P(q, sp, contrib=[{'v': 900.0}, {'v': 600.0}]), ext, q=q)
        ok(d and d[0][3] == '주인', f'남의 돈을 섞어 셌는데 못 잡음 {d}')

    # 12) 금액 표현 읽기 — 정규식과 따로 읽는 넉넉한 읽기
    for t, v in (('1억2천', 12000), ('8백50만', 850), ('148만 5천 원', 148.5), ('50,000원', 5), ('3천', 3000),
                 ('2천5백', 2500), ('3천만 원', 3000), ('1,500만 원', 1500), ('1억', 10000), ('30', 30)):
        ok(abs(cc._amount_value(t) - v) < 1e-6, f'금액 읽기 {t} → {cc._amount_value(t)} (기대 {v})')
    got = [round(x[0], 1) for x in cc._amounts_in('62살이고 2년차, 12월에 16.5% 떼고 3천 2년차 월 70')]
    ok(got == [3000, 70], f'나이·연차·달·비율을 금액으로 읽음 {got}')

    # 13) 모델 JSON 고치기 — man 칸에 셈식·쉼표 숫자·맨 글자를 적어도 확인을 건너뛰지 않는다
    outs = ['```json\n{"amounts": [{"text": "연금저축 월 110", "man": 110 * 12, "use": "연금수령"}], "age": 72}\n```',
            '{"amounts": [{"text": "월 5만", "man": 50,000, "use": "납입"}, {"text": "IRP", "man": 모름, "use": "납입"}]}']
    real = cc.clova.chat
    try:
        cc.clova.chat = lambda *a, **k: outs.pop(0)
        e1, e2 = cc.extract('x'), cc.extract('y')
    finally:
        cc.clova.chat = real
    ok(e1 and e1['amounts'][0]['man'] == 1320, f'셈식 man 을 못 고침 {e1}')
    ok(e2 and e2['amounts'][0]['man'] == 50000 and e2['amounts'][1]['man'] is None, f'쉼표 숫자·맨 글자 man 을 못 고침 {e2}')

    # 14) check() 연결 — 계산 블록·정규식 읽기는 손으로(taxcalc 가 고쳐져 300을 읽게 돼도 연결 시험은 돈다)
    q = '연금저축 계좌가 두 개예요. A에 300, B에 400 넣었고 IRP엔 200 넣었어요. 총급여 5천이면 공제 얼마?'
    c = {'blocks': [{'numbers': True}],
         'parsed': P(q, [('400', 400, 'contrib'), ('200', 200, 'contrib'), ('총급여 5천', 5000, 'income')])}
    real = cc.extract
    try:
        cc.extract = lambda *a, **k: A(('300', 300, '납입'), ('400', 400, '납입'), ('200', 200, '납입'))
        r = cc.check(q, c)
        cc.extract = lambda *a, **k: A(('400', 400, '납입'), ('200', 200, '납입'))
        r2 = cc.check(q, c)
    finally:
        cc.extract = real
    ok(r and "'300'" in r['message'] and all(len(x) == 4 for x in r['diffs']), f'check 가 못 읽은 금액을 되묻지 않음 {r}')
    ok(r2 is None, f'두 읽기가 같은데 되물음 {r2}')
    ok(bool(r) and json.dumps(r['diffs'], ensure_ascii=False), '서버가 trace 로 내보낼 수 없는 diffs')

    print(f'{n - len(fail)}/{n} 통과')
    for f in fail:
        print('  ' + f)
    return 1 if fail else 0


