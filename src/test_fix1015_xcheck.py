    said = {u[0]: u[4] for u in cc.unread(p, ext, q)}
    msg = cc.message(d, p, said)
    ok(answer._XC_ASKED in msg, '확인 질문 첫 줄과 되묻기 반복 막기 표시가 어긋남(answer._XC_ASKED)')
    ok("'300'(300만 원)" in msg and '계산에 넣지 못했어요' in msg and '넣는 돈인 것 같아요' in msg,
       f'못 읽은 금액을 고객이 쓴 말로 짚지 않음: {msg}')
