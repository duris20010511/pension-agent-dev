"""10-15 금액 읽기 교차확인 — 정규식이 아예 못 읽은 금액(crosscheck.unread). 모델을 부르지 않는다(모델 출력은 손으로 만든 JSON).
정규식 읽기(parsed)도 손으로 만든다 — 다른 묶음이 taxcalc 를 고쳐 '못 읽음'이 '읽음'으로 바뀌어도 이 시험이 흔들리지 않게.
질문은 현실 질문 120개(sweep)의 틀린 숫자 12개와 같은 뜻 다른 표현(eval/paraphrase_set.json)에서 왔다."""
import json
import sys

import answer
import crosscheck as cc
import taxcalc


def P(q, spans, contrib=None):
    """손으로 만든 정규식 읽기 — spans: (질문 속 글, 만 원 값, 역할[, 기간[, 출처]])."""
    qn = taxcalc.normalize(taxcalc.norm_ws(q))
    out = []
    for t, v, role, *rest in spans:
        s = qn.find(t)
        assert s >= 0, (q, t)
        out.append({'v': v, 's': s, 'e': s + len(t), 'role': role, 'period': rest[0] if rest else None, 'kind': None,
                    'src': rest[1] if len(rest) > 1 else None})
    return {'spans': out, 'contrib': contrib or [], 'age': None}


def A(*items):
    """손으로 만든 HCX-005 뽑기 — (text, man, use[, period[, whose]])."""
    return {'amounts': [dict(zip(('text', 'man', 'use', 'period', 'whose'), it)) for it in items]}


