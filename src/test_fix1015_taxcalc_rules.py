def calc(q):
    return taxcalc.compute(q)


def key(q):
    c = calc(q)
    return [b.get('key_figure') for b in c['blocks']] if c else None


def topics(q):
    c = calc(q)
    return [b['topic'] for b in c['blocks']] if c else None


def body(q):
    c = calc(q)
    return '\n'.join(b['text'].split('\n[원문]')[0] for b in c['blocks']) if c else ''


def needs(q):
    c = calc(q)
    return c['needs'] if c else []


