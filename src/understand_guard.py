# -*- coding: utf-8 -*-
"""
③ 질의이해 + ⑥ 가드 — 규칙 기반 기준선.

LLM(HyperCLOVA X) 없이도 돌아가는 baseline 을 먼저 만든다.
나중에 LLM 판정으로 바꿨을 때 '얼마나 좋아졌는지'를 재려면 비교 대상이 있어야 한다.
"""
import re

# ---------------------------------------------------------------- ③ 질의이해
CATEGORY_HINTS = {
    '세제': ['세액공제', '연금소득세', '종합과세', '분리과세', '과세이연', '퇴직소득세',
             '세금', '절세', '공제', '과세', '비과세', '원천징수', '연말정산', '수령한도', '수령연차'],
    '제도': ['DB', 'DC', 'IRP', '확정급여', '확정기여', '규약', '가입대상', '가입자',
             '평균임금', '계속근로', '압류', '지연이자', '가입자교육', '근로자대표', '실물이전'],
    '상품비교': ['비교', '차이', '뭐가 달라', '뭐가 다른', '어떤 게', '중에', '대비'],
    '상품설명': ['위험등급', '총보수', '클래스', '수익률', '펀드', '설정액', '보수', '투자대상'],
    '조건부추천': ['추천', '골라', '뭐가 좋', '어떤 걸 사', '괜찮은', '유리한'],
    '절차': ['어떻게 신청', '절차', '방법', '신청하', '어디서', '서류', '해지', '이체', '인출'],
}

# 확정 답변에 필요한 조건이 빠졌을 때 나타나는 신호
UNDERSPEC = [
    (r'추천|골라|어떤\s*(?:걸|것|상품)', '계좌유형·투자기간·감내 위험'),
    (r'얼마(?:나|를)?\s*(?:받|나오|되)', '금액 산정에 필요한 조건'),
    (r'제일|가장\s*(?:좋|나은|유리)', '비교 기준'),
]
CONCRETE = r'\d|IRP|연금저축|DB|DC|퇴직연금|만\s*\d+세|총급여|원|%'


def classify(q):
    """유형 분류. 힌트 매칭 점수가 가장 높은 유형."""
    scores = {}
    for cat, kws in CATEGORY_HINTS.items():
        s = sum(1 for k in kws if k.lower() in q.lower())
        if s:
            scores[cat] = s
    if not scores:
        return '종합'
    return max(scores.items(), key=lambda x: (x[1], x[0] == '세제'))[0]


def needs_clarification(q):
    """역질문이 필요한가. (필요여부, 무엇을 되물을지)"""
    for pat, what in UNDERSPEC:
        if re.search(pat, q):
            # 구체적 조건이 이미 충분히 들어있으면 역질문 불필요
            if len(re.findall(CONCRETE, q)) >= 3:
                continue
            return True, what
    return False, ''


# ---------------------------------------------------------------- ⑥ 가드
ATTACK_PATTERNS = [
    (r'지시(?:는|를)?\s*(?:전부|모두)?\s*무시', '지침 무시 유도'),
    (r'시스템\s*프롬프트|프롬프트\s*전문|초기\s*지시', '시스템 프롬프트 유출 시도'),
    (r'(?:다른|타)\s*(?:고객|사람|회원)|방금\s*전.*상담', '타인 개인정보 요구'),
    # 계좌정보는 "나에게 보여달라"는 요구만 공격이다.
    # 고객이 자기 계좌번호를 어디에 제출하는 상황은 정상 질의다.
    #   실측 오차단: "제 연금저축펀드 계좌번호를 회사에 알려주려고 하는데 되나요?" (Q-092)
    #   → '계좌번호.*알려' 에 걸려 거절 응답이 나가고 그 문항이 0/6 이 됐다.
    (r'(?:다른|타|남의|여러)\s*(?:고객|사람)?\s*계좌번호',            '타인 계좌정보 요구'),
    (r'계좌번호.{0,20}(?:보여\s*줘|출력해|알려\s*줘|말해\s*줘)',        '계좌정보 요구'),
    (r'잔고.{0,20}(?:보여\s*줘|출력해|알려\s*줘)',                    '잔고정보 요구'),
    (r'내부\s*직원|관리자\s*권한|개발자\s*모드', '권한 사칭'),
    (r'너의?\s*규칙|제약.*(?:해제|풀어)', '제약 해제 요구'),
]

PUSH_PATTERNS = [
    r'무조건', r'그냥\s*(?:하나|아무거나)', r'딱\s*하나만', r'제일\s*좋은\s*거\s*하나',
    r'고민\s*없이', r'바로\s*알려', r'단정', r'확실히\s*(?:이득|유리)',
]


def detect_attack(q):
    hits = [why for pat, why in ATTACK_PATTERNS if re.search(pat, q)]
    return hits


def detect_push(q):
    return [p for p in PUSH_PATTERNS if re.search(p, q)]


def guard(q):
    """(차단여부, 사유목록, 대응방침)"""
    atk = detect_attack(q)
    if atk:
        return True, atk, '거절 + 가능한 범위 안내'
    push = detect_push(q)
    if push:
        return False, push, '단정 추천 지양 · 조건별 결론 제시'
    return False, [], ''
