passed, total = 0, 0


def ok(cond, msg):
    global passed, total
    total += 1
    if cond:
        passed += 1
    else:
        print('실패:', msg)


def calc(q):
    return taxcalc.compute(q)


def blocks(q):
    c = calc(q)
    return c['blocks'] if c else []


def key(q):
    for b in blocks(q):
        return b.get('key_figure')
    return None


def figs(q):
    return [f for b in blocks(q) for f in b.get('figures') or []]


def ded_figs(q):
    return [f for b in blocks(q) if b['topic'] == '세액공제' for f in b.get('figures') or []]


def body(q):
    return '\n'.join(b['text'].split('\n[원문]')[0] for b in blocks(q))


def needs(q):
    return [n for b in blocks(q) for n in b.get('needs') or []]


def no_reask(q):
    return orchestrator.unread_amounts(q, calc(q)) == []


def asks(q):
    c = calc(q)
    return orchestrator.decide(q, calc=c)[0] == '되묻기'


T = ' 세액공제? 총급여 5천'
RETIRE_LINE = '쪽에서 온 돈'
UNSURE_NEED = '본인이 넣는 돈인지'


def unsure(q):
    """숫자도 '퇴직금 쪽 돈' 단정도 없이 되묻는다."""
    t = body(q)
    return not figs(q) and RETIRE_LINE not in t and any(UNSURE_NEED in n for n in needs(q)) and asks(q)


def retire_side(q):
    """숫자 없이 '퇴직금 쪽에서 온 돈'(세액공제 납입 아님)."""
    t = body(q)
    return not figs(q) and RETIRE_LINE in t and '49만 5천 원' not in t


