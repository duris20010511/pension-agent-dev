# -*- coding: utf-8 -*-
"""
10-14 5차 검토 — fixers5 묶음(verify.fix_over1500 의 '초과분' 규칙 가르기) 회귀 시험. API 호출 없음.

    python src/test_fix1014_fixers5.py

4차 고침 뒤 맞는 한도 규칙 답에 1,500만 원 바로잡기 줄이 붙었다.
  421·422·423 — 초과액 대조에서 '800만 원이 초과분'·'1,500만 원이 초과분'의 '이 초과분'을 '이 초과하면' 같은 기준으로 봐
               규칙 계산의 초과액(인출 − 한도)을 못 찾았다. calc 가 없을 때도 초과분 금액으로 쓴 1,500만을 기준으로 봤다.
  424 — 초과분 뒤 '분리과세'를 모두 1,500만 원 규칙의 과세 방식 선택으로 봐 '한도 초과분 500만 원은 16.5% 기타소득세로
        분리과세돼요'에 줄이 붙었다. 기타소득은 무조건 분리과세다(doc21 33행, doc2 30행, doc36 24행).
이제
  - 기타소득·연금외수령·퇴직소득을 말한 꼬리에서는 종합과세·'선택'이 있을 때만 1,500만 원 규칙의 과세 방식으로 본다.
  - '이/가' 뒤의 '초과분·초과액'은 기준이 아니라 금액이다. '초과분' 바로 앞 '1,500만 원이/은'도 기준으로 세지 않는다.
  - '사적연금소득'을 한 말로 잡는다('사적연금'만 잡아 '사적연금소득이 1,500만'을 이름 없는 1,500만으로 봤다).
1,500만 원 규칙 오류('1,500만 원을 넘으면 초과분 + 종합과세·분리과세 선택', 연금소득·사적연금소득으로 부른 기준)는 계속 바로잡는다.
"""
import os
import subprocess
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
sys.stdout.reconfigure(encoding='utf-8')

import taxcalc
import verify

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
passed, total = 0, 0


def ok(cond, msg):
    global passed, total
    total += 1
    if cond:
        passed += 1
    else:
        print('실패:', msg)


def fixed(a, calc=None):
    """바로잡기 줄이 한 번 붙었는가."""
    out, k = verify.fix_over1500(a, calc)
    return k == 1 and out.endswith(verify.OVER1500_NOTE) and out.count(verify.OVER1500_NOTE) == 1


def kept(a, calc=None):
    out, k = verify.fix_over1500(a, calc)
    return k == 0 and out == a


Q = '만 62세, IRP 평가액 {}, 연금수령연차 3년차예요. 올해 {} 빼면 세금이 얼마예요?'
CDEMO = taxcalc.compute(Q.format('1억 원', '2,000만 원'))
C1227 = taxcalc.compute(Q.format('8,000만 원', '2,700만 원'))
C1220 = taxcalc.compute(Q.format('8,000만 원', '2,000만 원'))
C1230 = taxcalc.compute(Q.format('8,000만 원', '3,000만 원'))
for c, want in ((CDEMO, ([1500.0], 2000.0)), (C1227, ([1200.0], 2700.0)), (C1220, ([1200.0], 2000.0)),
                (C1230, ([1200.0], 3000.0))):
    ok(verify.calc_limits(c) == want, f'calc 한도·인출이 {want} 가 아님: {verify.calc_limits(c)}')
CALCS = (None, CDEMO, C1227, C1220, C1230)

# ── 421·422 — 초과액이 마침 1,500만 원(한도 1,200만·인출 2,700만)인 맞는 한도 답
S421 = '올해 연금수령한도는 1,200만 원이에요. 2,700만 원 중 1,500만 원이 초과분이라 16.5% 기타소득세예요.'
S422 = '연금수령한도는 1,200만 원이라 2,700만 원을 빼면 1,500만 원이 초과분으로 16.5% 기타소득세가 붙어요.'
for s in (S421, S422):
    ok(kept(s, C1227), f'421·422: calc 1,200/2,700 의 맞는 한도 답에 바로잡기 줄 — {s}')
    ok(kept(s), f'421·422: 초과분 금액으로 쓴 1,500만을 기준으로 봄(calc 없음) — {s}')

# ── 423 — 1,500만이 우연이 아닌 calc(초과액 800만·1,800만) — '800만 원이 초과분'의 800만도 초과액이다
S423 = [(C1220, '연금소득 1,500만 원 기준(종합과세 선택)은 한도 안 연금에만 따져요. 올해 한도는 1,200만 원이에요. '
                '2,000만 원 중 800만 원이 초과분이라 16.5% 기타소득세예요.'),
        (C1220, '올해 연금수령한도는 1,200만 원이에요. 연 1,500만 원 종합과세 기준과는 별개예요. '
                '2,000만 원을 빼면 800만 원이 초과분이 돼 16.5% 기타소득세가 붙어요.'),
        (C1230, '올해 연금수령한도는 1,200만 원이에요. 연 1,500만 원 종합과세 기준과는 별개예요. '
                '3,000만 원을 빼면 1,800만 원이 초과분이 돼 16.5% 기타소득세가 붙어요.')]
for c, s in S423:
    ok(kept(s, c), f'423: calc {verify.calc_limits(c)} 의 맞는 한도 답에 바로잡기 줄 — {s[-60:]}')
# '이/가 초과분·초과액'은 금액, '을/를/이 넘'·'초과하면'·조사 없는 '초과분'은 기준
s = '2,000만 원 중 800만 원이 초과분이라 16.5% 기타소득세예요.'
ok(verify._states_excess(s, verify._PART_ONLY.search(s), [800.0]), "423: '800만 원이 초과분'의 800만을 초과액으로 못 셈")
for s in ('1,500만 원을 넘는 초과분은 16.5% 기타소득세예요.', '1,500만 원이 넘는 초과분은 16.5% 기타소득세예요.',
          '1,500만 원 초과분만 16.5%예요.', '1,500만 원을 초과하면 초과분은 16.5%예요.'):
    ok(not verify._states_excess(s, verify._PART_ONLY.search(s), [1500.0]), f'기준으로 쓴 1,500만을 초과액으로 셈 — {s}')

# ── 424 — 기타소득세·연금외수령에 붙은 '분리과세'·'과세 방식'은 과세 방식 선택이 아니다(doc21 33행·doc2 30행·doc36 24행)
H = '연금수령한도는 1,500만 원이에요. '
S424 = ['연금수령한도 초과분 500만 원은 16.5% 기타소득세로 분리과세돼요.',
        '한도 초과분 500만 원은 기타소득으로 분리과세돼 16.5%를 내요.',
        '연금수령한도 초과분은 연금외수령이라 16.5% 기타소득세가 분리과세돼요.',
        '한도 초과분 500만 원은 기타소득세(분리과세, 16.5%)예요.',
        '연금수령한도 초과분 500만 원은 과세 방식이 달라져 16.5% 기타소득세가 붙어요.',
        '연금수령한도 초과분 500만 원은 기타소득세 16.5%(분리과세)예요.']
for s in S424:
    for c in CALCS:
        ok(kept(H + s, c), f'424: 맞는 한도 문장에 바로잡기 줄(calc {verify.calc_limits(c)}) — {s}')
# 초과액이 1,500만 원인 calc 에서 '연금수령한도 초과분 1,500만 원은 … 기타소득세로 분리과세'
for s in ('올해 연금수령한도는 1,200만 원이고 2,700만 원 중 1,500만 원이 한도를 넘어요. '
          '연금수령한도 초과분 1,500만 원은 16.5% 기타소득세로 분리과세돼요.',
          S421 + ' 연금수령한도 초과분 1,500만 원은 16.5% 기타소득세로 분리과세돼요.'):
    ok(kept(s, C1227), f'424: calc 1,200/2,700 맞는 한도 문장에 바로잡기 줄 — {s[-50:]}')
    ok(kept(s), f'424: calc 없이 맞는 한도 문장에 바로잡기 줄 — {s[-50:]}')
# 퇴직금 재원도 한도 초과분은 퇴직소득세로 분리과세(doc39 35행, doc22 '이연퇴직소득 (분리과세)')
ok(kept('연금수령한도 1,500만 원을 넘는 초과분은 퇴직소득세로 분리과세돼요.'), '424: 한도 초과분 퇴직소득세 분리과세 문장에 줄')

# ── 1,500만 원 규칙 오류는 계속 바로잡는다 — 종합과세·선택을 말하거나 연금소득·사적연금소득으로 기준을 부른 문장
STILL = ['연금소득이 1,500만 원을 넘으면 초과분은 16.5% 기타소득세로 분리과세돼요.',
         '1,500만 원 초과분은 16.5% 기타소득세 또는 종합과세를 선택해요.',
         '연간 1,500만 원을 넘으면 초과분은 종합과세 대신 16.5% 기타소득세로 분리과세할 수 있어요.',
         '1,500만 원 초과분만 분리과세 16.5%예요.',
         '연금 3,000만 원을 받으면 1,500만 원이 초과분이라 16.5% 분리과세를 골라요.',
         '연금소득이 1,500만 원이 넘으면 초과분은 16.5% 기타소득세예요.',
         '1,500만 원이 넘는 초과분은 종합과세예요.',
         '사적연금소득이 1,500만 원을 넘으면 초과분은 기타소득세(분리과세, 16.5%)예요.',
         '연금소득이 1,500만 원을 넘으면 초과분은 과세 방식이 달라져 16.5% 기타소득세가 붙어요.',
         '연금소득 1,500만 원 초과분은 기타소득으로 분리과세돼요.',
         '1,500만 원을 초과하면 초과분은 종합과세 또는 16.5% 기타소득세 분리과세 중 고를 수 있어요.',
         '1,500만 원이 초과분이라 종합과세돼요.',
         '사적연금소득 한도 1,500만 원을 넘으면 초과분은 16.5% 기타소득세예요.']
for s in STILL:
    for c in CALCS:
        ok(fixed(s, c), f'1,500만 원 규칙 오류를 놓침(calc {verify.calc_limits(c)}) — {s}')
# 한도가 1,500만이 아닌 calc·calc 없음에서는 이름 없는 '1,500만 원을 넘으면 초과분 기타소득'도 계속 바로잡는다(2차 113)
for c in (None, C1227, C1220, C1230):
    ok(fixed('1,500만 원을 넘으면 초과분은 기타소득으로 분리과세돼요.', c), f'2차 113 꼴을 놓침(calc {verify.calc_limits(c)})')
# 저장된 답 _cfg_v3k10 — '종합과세: 사적연금소득(1,500만원 초과분) + 타 소득 합산'(초과분만 합산 오류)을 시연 calc 에서도 잡는다
S_CFG = '- **종합과세**: 사적연금소득(1,500만원 초과분) + 타 소득 합산 후 **최소 6.6%~최대 49.5%** 세율 적용 [1].'
for c in (None, CDEMO):
    ok(fixed(S_CFG, c), f"'사적연금소득(1,500만원 초과분)' 문장을 놓침(calc {verify.calc_limits(c)})")

# ── '사적연금소득'은 한 말 — 남은 '소득이'가 끼어 이름 없는 1,500만·연금수령한도로 보지 않는다
for s, k in (('사적연금소득이 1,500만 원을 넘으면 ', 'R'), ('사적연금소득 한도', 'R'), ('사적연금소득 한도 1,500만 원', 'R'),
             ('사적연금 한도', 'R'), ('사적연금 계좌 한도', 'L')):
    for d in (False, True):
        ok(verify._basis_kinds(s, d)[-1][1] == k, f"'{s}'(declared={d})의 종류가 {k} 가 아님: {verify._basis_kinds(s, d)}")
ok(not verify._basis_kinds('사적연금소득세 '), "'사적연금소득세'를 1,500만 원 규칙 말로 봄")

# ── 이전 차수 시험(fixers ~ fixers4)이 그대로 통과하는가
for name in ('fixers', 'fixers2', 'fixers3', 'fixers4'):
    p = os.path.join(ROOT, 'src', f'test_fix1014_{name}.py')
    r = subprocess.run([sys.executable, p], capture_output=True, text=True, encoding='utf-8',
                       env=dict(os.environ, PYTHONIOENCODING='utf-8'))
    last = (r.stdout.strip().splitlines() or [''])[-1]
    ok(r.returncode == 0, f'{name} 시험 실패: {last}\n{r.stdout[-800:]}{r.stderr[-400:]}')

print(f'{passed}/{total} 통과')
sys.exit(0 if passed == total else 1)
